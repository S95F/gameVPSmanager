// templatesFS holds the unit templates.
//
// They are files rather than string constants so that a golden test diffs a
// template against its output and an operator reading a bug report can be
// pointed at one file. They are EMBEDDED rather than read from /usr/share so
// that a box whose package data was wiped by a bad upgrade can still render a
// unit -- the same reason games/embed.go exists.
//
//go:embed templates/*.tmpl
var templatesFS embed.FS

// unitTemplates is parsed once. A parse failure is a build-time bug in a file
// this package owns, so it panics rather than returning an error every caller
// would have to ignore.
// The templates carry no functions on purpose. Everything that needs
// formatting -- seconds, byte sizes, wrapped comment lines -- is formatted in
// Go, where it is testable, so a template is only ever a layout.
var unitTemplates = template.Must(template.New("units").ParseFS(templatesFS, "templates/*.tmpl"))

// The names the templates define. They are constants so a rename shows up as a
// compile error at the call site rather than as an empty file at 3am.
const (
	tmplDropIn      = "dropin.tmpl"
	tmplTimer       = "timer.tmpl"
	tmplAdoptGuard  = "adopt-guard"
	tmplLegacyGuard = "legacy-guard"
)

// GeneratedHeader is the first line of every file this package writes.
//
// It is a constant because `gvm doctor` looks for it: a file under
// /etc/systemd/system/gvm@<name>.service.d that does NOT start with this line
// is an operator's, and gvm must report it rather than overwrite it.
const GeneratedHeader = "# GENERATED BY `gvm apply` -- DO NOT EDIT."

// renderedPrefix marks the one header line that changes on every render.
//
// It has to be recognisable because of what it costs otherwise: a timestamp in
// the file means every apply produces different bytes, every apply therefore
// writes, every write bumps the mtime, and the reconciler's single
// daemon-reload then looks like it had a reason on a box where nothing
// changed. SameDropIn compares everything except this line.
const renderedPrefix = "# rendered    "

// LocalDropIn is the operator's file in the same directory. gvm never writes,
// reads or deletes it (section 5.3); doctor reports its existence so that a
// merged unit nobody can explain is at least attributable.
const LocalDropIn = "90-local.conf"

// Credential is one systemd credential the unit loads (D-02).
//
// ID is the store's spelling (`rcon`) and Path is the file under
// /etc/gvm/secrets. The template spelling (`rcon_password`) never appears in a
// unit file: secrets.FromTemplate is the one place the two namespaces meet.
type Credential struct {
	ID   string
	Path string
}

// Sandbox is the confinement half of the drop-in, and it is the SAME value the
// write-probe runs against (D-15).
//
// One value feeding both is the property that matters. A probe built from its
// own idea of the sandbox would answer a question nobody asked -- and the
// failure it exists to catch, an adopted world under /home hidden by
// ProtectHome, is invisible until the game cannot save.
type Sandbox struct {
	// ProtectHome is always emitted explicitly, never left to the template's
	// default (D-15). `read-only` is the template's value and makes
	// /home/pzserver/Zomboid unwritable; `yes` makes /home EMPTY.
	ProtectHome string

	// ProtectSystem is restated from the shipped template so the transient
	// probe unit carries the same confinement. It is not written into the
	// drop-in, because the template already sets it and a second copy is a
	// second thing to keep in step.
	ProtectSystem string

	// Paths is the set the game must be able to write, in the order an
	// operator reads them: the install tree, the world, then the derived
	// directories.
	Paths []string

	// HomeReason is the comment the drop-in carries above ProtectHome, as
	// whole lines. It names the PATH that forced the value, because "why is
	// ProtectHome=no on this one server" is the question a security review
	// asks first and "because it is adopted" is not an answer.
	HomeReason []string
}

// homeRoot is the directory ProtectHome governs.
//
// ProtectHome also covers /root and /run/user, but neither can hold a game
// tree that gvm would manage: /root is refused by the destroy jail's system
// roots and /run/user is a session mount that does not survive a reboot.
const homeRoot = "/home"

// BuildSandbox decides the confinement for one instance.
//
// The rule is stated once, here, and both the drop-in and the probe read it:
// ProtectHome=no exactly when something the game must write lives under /home,
// and ProtectHome=yes otherwise. `read-only` is deliberately never chosen --
// it is the template's default and the value that produced the failure D-15
// exists to catch, so a generated file that selected it would be indis-
// tinguishable from a generated file that forgot to decide.
func BuildSandbox(in *spec.Instance) (Sandbox, error) {
	if in == nil {
		return Sandbox{}, fmt.Errorf("%w: no instance", ErrPlan)
	}
	name := in.Metadata.Name
	if err := instance.ValidateName(name); err != nil {
		return Sandbox{}, err
	}
	p := instance.PathsFor(name)

	logs := in.Spec.Paths.Logs
	if logs == "" {
		logs = p.Logs
	}
	// The set is exactly what the GAME writes. /var/backups/gvm/<name> is
	// 0700 root:root (D-44) and /var/lib/gvm/instances/<name> is 0750
	// root:root (section 5.3, "a compromised mod must not be able to rewrite
	// content.lock.json"); listing either would make the write-probe fail on
	// every real host for a write the instance user must never be able to
	// make.
	paths := dedupe([]string{
		in.Spec.Paths.Install,
		in.Spec.Paths.Data,
		logs,
		in.Spec.Paths.Work,
	})
	if len(paths) == 0 {
		return Sandbox{}, fmt.Errorf("%w: %s names no install or data path", ErrPlan, name)
	}

	sb := Sandbox{ProtectHome: "yes", ProtectSystem: "full", Paths: paths}
	for _, path := range paths {
		if underHome(path) {
			sb.ProtectHome = "no"
			sb.HomeReason = []string{
				path + " is under " + homeRoot + ", which the template's",
				"ProtectHome=read-only would hide. That is the adopted-instance failure D-15",
				"exists to catch: the server starts, runs, and cannot write its own save.",
			}
			break
		}
	}
	if sb.ProtectHome == "yes" {
		sb.HomeReason = []string{
			"Nothing this instance writes is under " + homeRoot + ", so the whole directory",
			"stays invisible to it. Emitted explicitly rather than left to the template,",
			"because a value nobody chose is a value nobody checked.",
		}
	}
	return sb, nil
}

// underHome reports whether p is /home or lives inside it.
func underHome(p string) bool {
	return p == homeRoot || strings.HasPrefix(p, homeRoot+"/")
}

// DropInInput is everything RenderDropIn needs that it cannot derive.
type DropInInput struct {
	Instance *spec.Instance
	// Manifest is the PINNED manifest -- the bytes under
	// /etc/gvm/instances/<name>.d/manifest.lock.yaml, not whatever the
	// catalog resolves today. The drop-in's header names its revision and
	// sha256, and a header that named a manifest the runner will not load
	// would be worse than no header (D-17).
	Manifest *spec.Manifest

	// SpecSHA is the sha256 of the instance YAML bytes, hex. It is supplied
	// rather than computed because the bytes that matter are the ones about
	// to be WRITTEN, which the caller holds and this function does not.
	SpecSHA string

	// HasSecret reports whether a credential exists on disk. It is a seam
	// because of what systemd does when it does not: LoadCredential= naming
	// an absent file makes the unit fail to start outright, which would
	// replace the runner's careful "these three credentials are missing"
	// preflight with a unit that never runs. Absent credentials are named in
	// a comment instead. A nil func means "none exist yet", which is what a
	// fresh `gvm create` sees.
	HasSecret func(id string) bool

	Now     time.Time
	Version string
}

// dropInModel is the template's view. Every value that needs formatting is
// formatted here, so the template contains no arithmetic and no conditionals
// beyond "is this section present".
type dropInModel struct {
	SpecPath    string
	SpecSHA     string
	Game        string
	Revision    int
	ManifestSHA string
	Origin      string
	Rendered    string
	Version     string

	Adopted    bool
	User       string
	Group      string
	UMask      string
	WorkingDir string

	Env         []envLine
	CredEnv     []string
	Sandbox     Sandbox
	PathsLine   string
	Creds       []Credential
	MissingLine string

	Resources spec.Resources
	SizeNote  []string

	Arch     string
	ArchNote []string
	MDWE     string
	MDWENote []string

	TimeoutStart int
	TimeoutStop  int
	TimeoutNote  string

	// EgressLines holds the IPAddressDeny= / IPAddressAllow= directives for
	// instances with spec.egress.policy=allowlist. Empty for open policy.
	EgressLines []string
}

type envLine struct{ Key, Value string }

// BuildDropIn resolves an instance into the drop-in's contents.
//
// It renders nothing to disk and touches no host state, so `gvm apply --diff`
// and `gvm apply` build the same value from the same inputs and cannot
// disagree about what would be written.
func BuildDropIn(in DropInInput) ([]byte, Sandbox, error) {
	if in.Instance == nil || in.Manifest == nil {
		return nil, Sandbox{}, fmt.Errorf("%w: BuildDropIn needs an instance and its pinned manifest", ErrPlan)
	}
	inst, m := in.Instance, in.Manifest
	name := inst.Metadata.Name
	sb, err := BuildSandbox(inst)
	if err != nil {
		return nil, Sandbox{}, err
	}
	pathsLine, err := joinPaths("ReadWritePaths", sb.Paths)
	if err != nil {
		return nil, Sandbox{}, err
	}

	group := inst.Spec.Group
	if group == "" {
		group = inst.Spec.User
	}
	for f, v := range map[string]string{
		"User":             inst.Spec.User,
		"Group":            group,
		"WorkingDirectory": inst.Spec.Paths.Install,
	} {
		if v == "" {
			return nil, Sandbox{}, fmt.Errorf("%w: %s is empty for %s", ErrPlan, f, name)
		}
		if err := checkUnitValue(f, v); err != nil {
			return nil, Sandbox{}, err
		}
	}

	// The three memory directives come from the same operator-typed file as
	// User, Group and WorkingDirectory above, and the template interpolates
	// them unquoted -- but nothing between the YAML and here looks at them:
	// spec.ValidateInstance has no rule for spec.resources, and
	// instance.CheckResources (which would re-parse them) has no production
	// caller. So they get the same check the rest of this file's operator-typed
	// values get. An EMPTY value is left alone deliberately: systemd reads a
	// bare `MemoryMax=` as reset-to-default, and most instances declare none.
	for f, v := range map[string]string{
		"MemoryHigh":    inst.Spec.Resources.MemoryHigh,
		"MemoryMax":     inst.Spec.Resources.MemoryMax,
		"MemorySwapMax": inst.Spec.Resources.MemorySwapMax,
	} {
		if v == "" {
			continue
		}
		if err := checkUnitValue(f, v); err != nil {
			return nil, Sandbox{}, err
		}
	}

	env, credEnv, err := buildEnv(inst, m)
	if err != nil {
		return nil, Sandbox{}, err
	}
	creds, missing, err := BuildCredentials(m, name, in.HasSecret)
	if err != nil {
		return nil, Sandbox{}, err
	}

	arch, archNote, err := archDirective(m.Spec.Runtime.Arch)
	if err != nil {
		return nil, Sandbox{}, err
	}

	start, err := deadlineSeconds("readiness.hard_deadline", m.Spec.Readiness.HardDeadline)
	if err != nil {
		return nil, Sandbox{}, err
	}
	stop, err := deadlineSeconds("shutdown.budget", m.Spec.Shutdown.Budget)
	if err != nil {
		return nil, Sandbox{}, err
	}

	now := in.Now
	if now.IsZero() {
		now = time.Now()
	}
	version := in.Version
	if version == "" {
		version = "dev"
	}

	md := dropInModel{
		SpecPath:     instance.PathsFor(name).Spec,
		SpecSHA:      in.SpecSHA,
		Game:         inst.Spec.Game,
		Revision:     m.Metadata.Revision,
		ManifestSHA:  shortSHA(inst.Spec.Manifest.SHA256),
		Origin:       string(inst.Spec.Manifest.Origin),
		Rendered:     now.UTC().Format(time.RFC3339),
		Version:      version,
		Adopted:      !inst.Spec.ManagedInstall,
		User:         inst.Spec.User,
		Group:        group,
		UMask:        "0027",
		WorkingDir:   inst.Spec.Paths.Install,
		Env:          env,
		CredEnv:      credEnv,
		Sandbox:      sb,
		PathsLine:    pathsLine,
		Creds:        creds,
		MissingLine:  missingLine(missing),
		Resources:    inst.Spec.Resources,
		SizeNote:     sizeNote(m, inst),
		Arch:         arch,
		ArchNote:     archNote,
		MDWE:         mdweValue(m.Spec.Runtime.JIT),
		MDWENote:     mdweNote(m.Spec.Runtime.JIT),
		TimeoutStart: start,
		TimeoutStop:  stop,
		TimeoutNote: fmt.Sprintf("readiness.hard_deadline=%s (D-12); shutdown.budget=%s",
			m.Spec.Readiness.HardDeadline, m.Spec.Shutdown.Budget),
		EgressLines: buildEgressDirectives(inst.Spec.Egress),
	}

	var buf bytes.Buffer
	if err := unitTemplates.ExecuteTemplate(&buf, tmplDropIn, md); err != nil {
		return nil, Sandbox{}, fmt.Errorf("reconcile: render drop-in for %s: %w", name, err)
	}
	return buf.Bytes(), sb, nil
}

// buildEnv renders the manifest's runtime env for the UNIT.
//
// Two things happen here that do not happen in the runner's copy of this
// render. The unit gets GVM_INSTANCE, because a human reading `ps` or a
// journal line needs to know which server a process belongs to. And a value
// that expands a secret is NOT written: Environment= is readable through
// `systemctl show` and /proc/<pid>/environ, so a password there is a password
// published, and the runner supplies it to the game from CREDENTIALS_DIRECTORY
// instead (D-02). The skipped key is named in a comment rather than dropped
// silently, because "why is LANG here and TELNET_PASSWORD not" is a fair
// question to ask of a generated file.
func buildEnv(inst *spec.Instance, m *spec.Manifest) ([]envLine, []string, error) {
	r := spec.NewRenderer(spec.RenderData{
		Name:    inst.Metadata.Name,
		Game:    inst.Spec.Game,
		Install: inst.Spec.Paths.Install,
		Data:    inst.Spec.Paths.Data,
		Home:    inst.Spec.Paths.Home,
		Work:    inst.Spec.Paths.Work,
		User:    inst.Spec.User,
		Group:   groupOf(inst),
		Port:    portValues(inst),
		Var:     varValues(inst),
		// Secret is deliberately empty. Rendering with the real values would
		// mean holding them in memory here only to refuse to write them, and
		// the taint flag says a secret was referenced without needing one.
		Secret: spec.SecretValues{},
		Phase:  spec.PhaseNormal,
	})

	keys := make([]string, 0, len(m.Spec.Runtime.Env))
	for k := range m.Spec.Runtime.Env {
		keys = append(keys, k)
	}
	sort.Strings(keys)

	var out []envLine
	var skipped []string
	for _, k := range keys {
		field := "spec.runtime.env." + k
		// The secret check happens BEFORE the render rather than on the
		// render's taint flag, because there is no secret map to render
		// against here and text/template refuses a missing key. Asking which
		// variables a template NAMES is the same question and needs no
		// values, which is also why this function never has to hold one.
		tainted, err := namesASecret(field, m.Spec.Runtime.Env[k])
		if err != nil {
			return nil, nil, err
		}
		if tainted {
			skipped = append(skipped, k)
			continue
		}
		v, _, err := r.Render(field, m.Spec.Runtime.Env[k])
		if err != nil {
			return nil, nil, fmt.Errorf("reconcile: %w", err)
		}
		if err := checkUnitValue("Environment="+k, v); err != nil {
			return nil, nil, err
		}
		if err := checkUnitValue("Environment key "+k, k); err != nil {
			return nil, nil, err
		}
		// Environment= separates ASSIGNMENTS on whitespace, exactly as
		// ReadWritePaths= separates paths, so the same rule applies: a value
		// with a space in it silently becomes two variables. The live route in
		// is Paths.Home -- every shipped manifest sets HOME: "{{ .Home }}",
		// --home is free-form, and Home is not in Sandbox.Paths, so neither
		// joinPaths nor the D-15 write-probe ever sees it. Refusing rather than
		// emitting systemd's quoted form follows joinPaths: a quoting rule has
		// to be right forever, and a multi-token value is already mis-parsed
		// today, so this surfaces existing breakage rather than causing any.
		if strings.ContainsAny(v, " \t\"'\\") {
			return nil, nil, fmt.Errorf("%w: Environment=%s = %q contains a space or a quote; "+
				"systemd separates this directive's assignments on whitespace, so this would "+
				"define a second variable", ErrUnsafeValue, k, v)
		}
		out = append(out, envLine{Key: k, Value: v})
	}
	out = append(out, envLine{Key: "GVM_INSTANCE", Value: inst.Metadata.Name})
	return out, skipped, nil
}

// namesASecret reports whether a templated field references `.Secret.*`.
//
// It asks the guarded parser rather than scanning for a substring: `{{ .Secret
// . rcon_password }}` and `{{.Secret.rcon_password}}` are the same reference
// and a substring match would eventually miss one of them.
func namesASecret(field, text string) (bool, error) {
	refs, terr := spec.TemplateRefs(field, text, spec.SurfaceFor(field))
	if terr != nil {
		return false, fmt.Errorf("%w: %s: %s", ErrPlan, field, terr.Msg)
	}
	for _, r := range refs {
		if r.Root == "Secret" {
			return true, nil
		}
	}
	return false, nil
}

func groupOf(inst *spec.Instance) string {
	if inst.Spec.Group != "" {
		return inst.Spec.Group
	}
	return inst.Spec.User
}

func portValues(inst *spec.Instance) spec.PortValues {
	out := spec.PortValues{}
	for k, v := range inst.Spec.Ports {
		out[k] = v
	}
	return out
}

func varValues(inst *spec.Instance) spec.VarValues {
	out := spec.VarValues{}
	for k, v := range inst.Spec.Vars {
		out[k] = v
	}
	return out
}

// BuildCredentials derives the LoadCredential= lines from the manifest's own
// `.Secret.<name>` references.
//
// Deriving rather than listing is the point: a hand-kept list stops covering a
// secret the day somebody adds one to a manifest, and the symptom is an empty
// RCONPassword in a live config file. The scan is spec.ScanManifestRefs, the
// same one `gvm run` uses to decide which credential ids to read back, so the
// unit cannot load a set the runner does not expect.
//
// A credential whose file does not exist is returned in `missing` and NOT
// emitted, because systemd fails a unit outright when LoadCredential= names an
// absent path -- which would replace the runner's "these credentials are
// missing" preflight with a server that will not start.
func BuildCredentials(m *spec.Manifest, name string, has func(string) bool) (creds []Credential, missing []string, err error) {
	refs, err := spec.ScanManifestRefs(m)
	if err != nil {
		return nil, nil, fmt.Errorf("reconcile: %w", err)
	}
	p := instance.PathsFor(name)
	ids := make([]string, 0, len(refs.Secrets))
	for _, tmpl := range refs.Secrets {
		id, err := secrets.FromTemplate(tmpl)
		if err != nil {
			return nil, nil, fmt.Errorf("reconcile: %s: %w", m.SourceRef, err)
		}
		ids = append(ids, id)
	}
	sort.Strings(ids)
	ids = dedupe(ids)

	for _, id := range ids {
		if has != nil && has(id) {
			creds = append(creds, Credential{ID: id, Path: p.Secret(id)})
			continue
		}
		missing = append(missing, id)
	}
	return creds, missing, nil
}

// archDirective turns the manifest's arch into SystemCallArchitectures=.
//
// A hardcoded `native` makes every 32-bit engine (Garry's Mod, L4D2, srcds)
// fail to start with no useful error, which is why the manifest declares it at
// all. `any` emits no directive: the filter is a restriction, and the honest
// way to say "do not restrict" is to not write one rather than to write
// something that means it.
func archDirective(arch string) (value string, note []string, err error) {
	switch arch {
	case "", "native":
		return "native", []string{
			"spec.runtime.arch=native. 32-bit engines (Garry's Mod, L4D2, srcds) set",
			"\"native x86\" from the manifest -- a hardcoded `native` here makes them fail to",
			"start with no useful error at all.",
		}, nil
	case "i386":
		return "native x86", []string{
			"spec.runtime.arch=i386. The engine is 32-bit, so x86 has to be admitted",
			"alongside the host's own architecture; with `native` alone every syscall the",
			"game makes is killed with SIGSYS before it prints anything.",
		}, nil
	case "any":
		return "", []string{
			"spec.runtime.arch=any, so no SystemCallArchitectures= is written. The directive",
			"is a restriction, and the honest way to say \"do not restrict\" is to write",
			"nothing rather than to write something that means it.",
		}, nil
	}
	return "", nil, fmt.Errorf("%w: spec.runtime.arch=%q is not native, i386 or any", ErrPlan, arch)
}

// missingLine names the credentials a manifest declares and the box does not
// have yet, in one line, so the generated file says why a LoadCredential= an
// operator expected is absent.
func missingLine(ids []string) string {
	if len(ids) == 0 {
		return ""
	}
	noun := "credential"
	if len(ids) > 1 {
		noun = "credentials"
	}
	return "no LoadCredential= for " + strings.Join(ids, ", ") + ": " + noun +
		" not present under /etc/gvm/secrets yet."
}

func mdweValue(jit bool) string {
	if jit {
		return "no"
	}
	return "yes"
}

// mdweNote is Project Zomboid's lesson, kept verbatim in the generated file.
//
// It is here rather than in a doc because the file it lands in is what a
// future security pass reads. "MemoryDenyWriteExecute=no looks wrong" is a
// correct instinct and a wrong conclusion for every JVM on the box.
func mdweNote(jit bool) []string {
	if jit {
		return []string{
			"spec.runtime.jit=true -- the JVM JIT needs W^X off. Do NOT \"harden\" this line",
			"to yes: it breaks every Java server on this box (Project Zomboid, Minecraft)",
			"with an obscure fault at class-load time. This line exists to survive a",
			"future security pass.",
		}
	}
	return []string{"spec.runtime.jit=false -- the engine compiles nothing at runtime."}
}

// sizeNote explains the memory numbers in the words of whoever chose them.
//
// The numbers themselves come from the INSTANCE, which an operator may edit,
// so the note also says when they no longer match what the manifest's sizing
// computes. A comment that silently described the manifest's arithmetic while
// the file above it carried an operator's number would be worse than none.
func sizeNote(m *spec.Manifest, inst *spec.Instance) []string {
	s := m.Spec.Sizing
	var lines []string
	switch s.Model {
	case "heap_plus_headroom":
		lines = append(lines, fmt.Sprintf("vars.%s %s + sizing.native_headroom %s is the hard ceiling.",
			s.HeapVar, inst.Spec.Vars[s.HeapVar], s.NativeHeadroom))
	default:
		lines = append(lines, fmt.Sprintf("sizing: %s, ram_floor %dM + native_headroom %s is the hard ceiling.",
			s.Model, s.RAMFloorMB, s.NativeHeadroom))
	}
	lines = append(lines,
		"MemoryHigh sits below it so the kernel throttles and reclaims first; crossing",
		"MemoryMax invokes the kernel OOM killer, which is the failure the headroom",
		"exists to prevent.")

	if want, err := instance.ComputeResources(m, varValues(inst)); err == nil {
		if want.MemoryMax != inst.Spec.Resources.MemoryMax || want.MemoryHigh != inst.Spec.Resources.MemoryHigh {
			lines = append(lines,
				fmt.Sprintf("EDITED: the manifest's sizing computes MemoryHigh=%s MemoryMax=%s and this",
					want.MemoryHigh, want.MemoryMax),
				"instance declares the values below. `gvm doctor` re-checks them.")
		}
	}
	return lines
}

// deadlineSeconds converts a manifest duration into the integer seconds a
// systemd timeout directive takes.
//
// It refuses zero and negative values rather than defaulting, because the
// default here is systemd's, and systemd's default TimeoutStartSec is 90
// seconds -- which would kill a Project Zomboid first boot at minute two of a
// forty-minute workshop download (D-12).
func deadlineSeconds(field string, d spec.Duration) (int, error) {
	sec := int(d.Duration() / time.Second)
	if sec <= 0 {
		return 0, fmt.Errorf("%w: %s is %s; it becomes a systemd timeout and must be finite "+
			"and positive (D-12)", ErrPlan, field, d)
	}
	return sec, nil
}

// shortSHA is the 8-character prefix the header carries.
//
// The full digest is on the `spec sha256` line; the manifest one is short
// because it is an identifier a human compares against `gvm game show`, and a
// 64-character hex string in a comment is a line nobody reads.
func shortSHA(s string) string {
	if len(s) <= 8 {
		return s
	}
	return s[:8]
}

// SpecSHA256 is the digest the drop-in header records.
//
// It is over the instance YAML bytes as written, so `sha256sum
// /etc/gvm/instances/pz-main.yaml` and the header line are the same string --
// which is the whole reason the header carries it: an operator can tell in one
// command whether the running unit was generated from the file in front of
// them.
func SpecSHA256(b []byte) string {
	sum := sha256.Sum256(b)
	return hex.EncodeToString(sum[:])
}

// SameDropIn compares two renderings ignoring the `# rendered` line.
//
// Without this, every apply writes: the timestamp differs, the bytes differ,
// hostops writes, the mtime moves, and the reconciler's daemon-reload looks
// like it had a reason on a box where nothing changed. With it, an apply that
// changes nothing says so.
func SameDropIn(a, b []byte) bool {
	return bytes.Equal(stripRendered(a), stripRendered(b))
}

func stripRendered(b []byte) []byte {
	lines := bytes.Split(b, []byte("\n"))
	out := lines[:0]
	for _, l := range lines {
		if bytes.HasPrefix(l, []byte(renderedPrefix)) {
			continue
		}
		out = append(out, l)
	}
	return bytes.Join(out, []byte("\n"))
}

// RenderAdoptGuard is 20-adopt.conf: the Conflicts= that makes systemd itself
// refuse to run the legacy unit and the gvm unit against the same world.
//
// It is a separate file from 10-gvm.conf and a separate owner (section 7.1's
// numbering contract): `gvm apply` rewrites the drop-in on every run, and the
// adoption guard is written once by `gvm adopt cutover` and removed once by
// `gvm adopt finalize`. It also could not live in the drop-in even if the
// numbering allowed it -- the legacy unit's NAME is not in the instance YAML,
// so the generator has nothing to render it from.
func RenderAdoptGuard(instanceName, legacyUnit string) ([]byte, error) {
	if err := instance.ValidateName(instanceName); err != nil {
		return nil, err
	}
	if err := checkUnitValue("legacy unit", legacyUnit); err != nil {
		return nil, err
	}
	return renderGuard(tmplAdoptGuard, instanceName, legacyUnit)
}

// RenderLegacyGuard is the reciprocal, written into the LEGACY unit's drop-in
// directory. Both halves exist because a Conflicts= in one direction is enough
// for systemd but not for an operator reading either unit and asking what
// stops the other one starting.
func RenderLegacyGuard(instanceName, legacyUnit string) ([]byte, error) {
	if err := instance.ValidateName(instanceName); err != nil {
		return nil, err
	}
	if err := checkUnitValue("legacy unit", legacyUnit); err != nil {
		return nil, err
	}
	return renderGuard(tmplLegacyGuard, instanceName, legacyUnit)
}

func renderGuard(name, instanceName, legacyUnit string) ([]byte, error) {
	var buf bytes.Buffer
	err := unitTemplates.ExecuteTemplate(&buf, name, struct {
		Instance, Unit, LegacyUnit string
	}{
		Instance:   instanceName,
		Unit:       instance.UnitName(instanceName),
		LegacyUnit: legacyUnit,
	})
	if err != nil {
		return nil, fmt.Errorf("reconcile: render %s: %w", name, err)
	}
	return buf.Bytes(), nil
}

// WantsLink is where systemd records that an instance's unit is enabled.
//
// The packaged template's [Install] section is WantedBy=multi-user.target, so
// `systemctl enable gvm@pz-main` creates exactly this symlink and disabling
// removes it. Reading it is the only way this build can tell an already-enabled
// unit from one that is not: platform.UnitState carries LoadState, ActiveState,
// SubState and Result, and no UnitFileState at all.
func WantsLink(name string) string {
	return "/etc/systemd/system/multi-user.target.wants/" + instance.UnitName(name)
}

// enabledOnHost answers whether the enablement symlink is present.
//
// The Inspector's Stat must NOT follow the link (the CLI's production one is
// an lstat): the target is /usr/lib/systemd/system/gvm@.service, and on a box
// where the package files are missing a following stat would report a unit
// that is enabled as not enabled -- which is a re-enable on every single apply
// and the loss of the property that makes apply safe to run when unsure.
func enabledOnHost(ins Inspector, name string) bool {
	if ins == nil {
		return false
	}
	_, err := ins.Stat(WantsLink(name))
	return err == nil
}

// enableAction is step 8's second half: make the boot behaviour match
// spec.enabled, and say nothing when it already does.
//
// The Unchanged branch is the whole point. `gvm apply` is meant to be the
// command an operator runs when they are not sure what state a box is in, and
// that only works if a converged host produces an empty plan; a step that
// always reads `~ unit enable` teaches them to ignore the one apply where it
// mattered. The verb is still ISSUED on the unchanged path -- hostops
// re-asserts it and systemd is idempotent about it -- because the symlink is
// evidence and not proof, and the cost of re-asserting is one dbus call.
func enableAction(in *spec.Instance, actor audit.Actor, host Host, ins Inspector) *UnitAction {
	name := in.Metadata.Name
	live := enabledOnHost(ins, name)

	if in.Spec.Enabled {
		a := &UnitAction{
			Instance: name, Verb: hostops.VerbUnitEnable, Actor: actor, Host: host,
			Note: "enabled at boot. The unit deliberately has no PartOf=gvm.target, so a " +
				"reboot brings the world back with the control plane and the database dead (D-14).",
		}
		if live {
			a.Change = Unchanged
			a.Note = "already enabled at boot; the enablement is re-asserted and nothing moves."
		}
		return a
	}
	a := &UnitAction{
		Instance: name, Verb: hostops.VerbUnitDisable, Actor: actor, Host: host,
		Note: "enabled: false, so the unit is disabled at boot. This does not stop a " +
			"running server; `gvm stop` does.",
	}
	if !live {
		a.Change = Unchanged
		a.Note = "enabled: false, and it is not enabled at boot. This does not stop a " +
			"running server; `gvm stop` does."
	}
	return a
}
