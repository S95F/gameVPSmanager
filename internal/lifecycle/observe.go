// Tri is a three-valued answer, and the third value is the point.
//
// Everything in this package that reads the host can fail to read it -- no
// /proc on a development machine, no D-Bus with the manager wedged, a status
// file that has not been written yet. A bool forces those into "false", and
// "false" is indistinguishable from a measured negative. Every rule in the
// phase table that would refuse, alarm or act on a negative therefore checks
// for No specifically, so that a host gvm could not question is reported as
// unknown rather than as broken.
type Tri uint8

const (
	// Unknown means nobody looked, or looking failed.
	Unknown Tri = iota
	// Yes means it was looked at and it is so.
	Yes
	// No means it was looked at and it is not so.
	No
)

func (t Tri) String() string {
	switch t {
	case Yes:
		return "yes"
	case No:
		return "no"
	}
	return "unknown"
}

// TriOf lifts a measured bool.
func TriOf(b bool) Tri {
	if b {
		return Yes
	}
	return No
}

// StatusStaleAfter is how long status.json may go unwritten before the unit
// being active stops being evidence that anything is running.
//
// The runner rewrites it every runner.StatusInterval (2 s) and on every
// transition, so this is thirty missed writes. It is generous on purpose: a
// box under a SteamCMD download can miss a handful, and a phase table that
// cried degraded during every backup would be turned off.
const StatusStaleAfter = 60 * time.Second

// generatedMarker is the first line of every file `gvm apply` writes into
// /etc/systemd/system.
//
// It is duplicated from internal/reconcile rather than imported, so that the
// observation half of the lifecycle does not drag the rendering half (and its
// templates, its archive dependency and its golden files) into every process
// that only wants to know what an instance is doing. The duplication is held
// in step by a test, which is where the coupling belongs.
const generatedMarker = "# GENERATED BY `gvm apply` -- DO NOT EDIT."

// localDropIn is the operator's own drop-in. Section 5.3: gvm never writes,
// reads or deletes it -- but doctor reports it, so an operator is not left
// wondering why a directive they cannot find in 10-gvm.conf is in effect.
const localDropIn = "90-local.conf"

// Files is the read-only filesystem the observer sees.
//
// It is an interface for one reason that matters: development happens on
// Windows and every path in section 5 is an absolute Linux path. A package
// that called os.ReadFile("/run/gvm/pz-main/status.json") directly would be
// testable only on the machine it is never developed on.
type Files interface {
	Stat(name string) (fs.FileInfo, error)
	ReadFile(name string) ([]byte, error)
	ReadDir(name string) ([]fs.DirEntry, error)
}

// UnitReader is the read-only half of the service manager.
//
// The reconciler holds one of these and not a platform.Systemd, and that is
// the structural form of "the reconciler never actuates": there is no Start to
// call. It is not a promise in a comment, it is a missing method
// (testdata/reconciler-actuates is the fixture that proves it stays missing).
type UnitReader interface {
	State(ctx context.Context, unit string) (platform.UnitState, error)
	ListUnits(ctx context.Context, pattern string) ([]platform.UnitState, error)
}

// Problem is something the observer could not establish.
//
// They are collected rather than returned, because an Observation with one
// unreadable source is still worth deriving a phase from: a status.json that
// will not parse should say so AND still let systemd's view be reported. What
// must never happen is a missing source silently becoming an absent fact,
// which is what a bare `if err != nil { continue }` produces.
type Problem struct {
	Source string `json:"source"`
	Path   string `json:"path,omitempty"`
	Detail string `json:"detail"`
}

// Pin is what could be established about the manifest pin (D-04).
//
// Present and OK are separate because a missing pin and a mismatched pin are
// different failures with different fixes: the first is an instance that was
// never applied, the second is `apt upgrade gvm` having shipped a new manifest
// under a live world.
type Pin struct {
	Present  bool   `json:"present"`
	OK       bool   `json:"ok"`
	Revision int    `json:"revision,omitempty"`
	SHA256   string `json:"sha256,omitempty"`
	Reason   string `json:"reason,omitempty"`
}

// DropInHeader is the header of the generated 10-gvm.conf (section 7.4).
//
// It is how "has this spec been applied" is answered with no database: apply
// writes the spec's sha256 into the file it generates, so the drop-in on disk
// carries its own provenance. instances.applied_sha256 mirrors this; it does
// not define it.
type DropInHeader struct {
	Generated   bool      `json:"generated"`
	SpecPath    string    `json:"spec_path,omitempty"`
	SpecSHA256  string    `json:"spec_sha256,omitempty"`
	Game        string    `json:"game,omitempty"`
	Revision    int       `json:"revision,omitempty"`
	ManifestSHA string    `json:"manifest_sha256,omitempty"`
	Origin      string    `json:"origin,omitempty"`
	Rendered    time.Time `json:"rendered,omitzero"`
	Version     string    `json:"version,omitempty"`
}

// Observation is everything the host says about one instance at one moment.
//
// It is a plain value with no methods that read anything. Derive takes it and
// returns a Phase, and a test can build any shape of it by hand -- including
// shapes a real host would take days to produce, like a lease from a previous
// boot over a unit that is still active.
type Observation struct {
	Name string    `json:"name"`
	Now  time.Time `json:"now,omitzero"`

	// Intent, from /etc/gvm/instances/<name>.yaml.
	SpecPresent    bool   `json:"spec_present"`
	SpecSHA256     string `json:"spec_sha256,omitempty"`
	Game           string `json:"game,omitempty"`
	Enabled        bool   `json:"enabled"`
	ManagedInstall bool   `json:"managed_install"`
	AdoptedFrom    string `json:"adopted_from,omitempty"`
	UnixUser       string `json:"unix_user,omitempty"`

	Pin Pin `json:"pin"`

	// What the last apply wrote, read back off the host.
	DropInPresent bool         `json:"dropin_present"`
	DropIn        DropInHeader `json:"dropin,omitzero"`
	LocalDropIn   bool         `json:"local_dropin"`

	// systemd. UnitChecked is separate from Unit because a zero UnitState is
	// indistinguishable from "inactive, cleanly", and reporting a manager gvm
	// could not reach as a stopped server is how an operator gets sent to
	// restart something that was never down.
	UnitChecked bool               `json:"unit_checked"`
	Unit        platform.UnitState `json:"unit,omitzero"`

	// The runner's own view (section 11.4). Nil means no status.json.
	Status        *runner.Status `json:"status,omitempty"`
	StatusModTime time.Time      `json:"status_modtime,omitzero"`

	// Markers under /run/gvm/<name>. All three are tmpfs and therefore
	// boot-scoped, which is exactly the lifetime each of them wants.
	Hold        bool   `json:"hold"`
	HoldReason  string `json:"hold_reason,omitempty"`
	FreezeLease bool   `json:"freeze_lease"`

	// BlockedMods is /var/lib/gvm/instances/<name>/blocked-mods.json: content
	// that needs a human to fetch it (section 12.8).
	BlockedMods bool `json:"blocked_mods"`

	// Installed is whether the provider's declared sentinel is on disk. It is
	// a Tri because a manifest gvm could not load has no sentinel to look
	// for, and "no sentinel declared" must not read as "not installed".
	Installed Tri `json:"installed"`

	// The job lease (section 5.3). LeaseState is Classify's answer, computed
	// where the boot id and the process table are readable; Derive consumes
	// the answer rather than re-deriving it, so the phase table stays free of
	// both.
	Lease           *Lease     `json:"lease,omitempty"`
	LeaseState      LeaseState `json:"lease_state,omitempty"`
	LeaseUnreadable bool       `json:"lease_unreadable,omitempty"`

	Problems []Problem `json:"problems,omitempty"`
}

// Observer gathers Observations. Every host-touching thing it does is a field,
// and every field has a harmless zero value.
type Observer struct {
	// FS is the filesystem. Nil is OSFiles.
	FS Files
	// Units is systemd. Nil means the unit state is not checked, which is
	// what a development machine and a `--offline` status get -- reported as
	// unknown rather than guessed at.
	Units UnitReader
	// Alive answers whether a pid is running. Nil means Unknown, and a lease
	// whose holder cannot be checked stays LIVE (see Lease.Classify).
	Alive func(pid int) Tri
	// BootID is this boot's id. Empty disables the boot check, which is the
	// safe direction: it can only make a lease look live.
	BootID string
	// Now is the clock. Nil is time.Now. It is injectable because the
	// status.json staleness rule is a comparison against it, and a test that
	// had to sleep for a minute to exercise it would not be written.
	Now func() time.Time
}

func (o *Observer) files() Files {
	if o.FS != nil {
		return o.FS
	}
	return OSFiles{}
}

func (o *Observer) now() time.Time {
	if o.Now != nil {
		return o.Now()
	}
	return time.Now()
}

// List returns the instance names, from /etc/gvm/instances/*.yaml.
//
// This is the ONLY enumeration of instances in gvm, and it never consults the
// database. Section 1's promise is that the control plane being dead changes
// nothing about the servers, and a sweep that could not enumerate without
// Postgres would break it in the one place where it matters most.
//
// The `.d` directories and the `.lock.json` files share the directory, so the
// filter is on the exact suffix and the name must be one instance.ValidateName
// accepts -- a stray backup.yaml.bak or an editor's swap file is skipped, and
// a file whose name is not a legal instance name is reported rather than
// silently ignored.
func List(f Files) ([]string, []Problem, error) {
	entries, err := f.ReadDir(spec.EtcInstancesDir)
	if err != nil {
		return nil, nil, err
	}
	var names []string
	var probs []Problem
	for _, e := range entries {
		if e.IsDir() {
			continue
		}
		n := e.Name()
		if !strings.HasSuffix(n, ".yaml") || strings.HasSuffix(n, ".lock.yaml") {
			continue
		}
		name := strings.TrimSuffix(n, ".yaml")
		if err := instance.ValidateName(name); err != nil {
			probs = append(probs, Problem{
				Source: "list",
				Path:   path.Join(spec.EtcInstancesDir, n),
				Detail: err.Error(),
			})
			continue
		}
		names = append(names, name)
	}
	sort.Strings(names)
	return names, probs, nil
}

// Observe reads everything about one instance.
//
// It returns an Observation and no error for anything it merely could not
// read: an unreadable source becomes a Problem and the observation continues.
// The one thing that stops it is a name that is not a legal instance name,
// because every path below is derived from it.
func (o *Observer) Observe(ctx context.Context, name string) (Observation, error) {
	if err := instance.ValidateName(name); err != nil {
		return Observation{}, err
	}
	f := o.files()
	p := instance.PathsFor(name)
	obs := Observation{Name: name, Now: o.now(), Installed: Unknown}

	inst := o.readSpec(f, p, &obs)
	m := o.readPin(f, p, inst, &obs)
	o.readDropIn(f, name, &obs)
	o.readUnit(ctx, name, &obs)
	o.readStatus(f, p, &obs)
	o.readMarkers(f, p, &obs)
	o.readInstalled(f, inst, m, &obs)
	o.readLease(f, name, &obs)
	return obs, nil
}

func (o *Observer) readSpec(f Files, p instance.Paths, obs *Observation) *spec.Instance {
	raw, err := f.ReadFile(p.Spec)
	if err != nil {
		if !errors.Is(err, fs.ErrNotExist) {
			obs.Problems = append(obs.Problems, Problem{Source: "spec", Path: p.Spec, Detail: err.Error()})
		}
		return nil
	}
	obs.SpecPresent = true
	obs.SpecSHA256 = sha256Hex(raw)
	in, _, err := spec.ParseInstance(p.Spec, raw)
	if err != nil {
		// The file is there and gvm cannot read it. That is a failure with a
		// fix (`gvm apply --diff` prints the diagnostics), not an absence.
		obs.Problems = append(obs.Problems, Problem{Source: "spec", Path: p.Spec, Detail: err.Error()})
		return nil
	}
	obs.Game = in.Spec.Game
	obs.Enabled = in.Spec.Enabled
	obs.ManagedInstall = in.Spec.ManagedInstall
	obs.AdoptedFrom = in.Metadata.AdoptedFrom
	obs.UnixUser = in.Spec.User
	return in
}

func (o *Observer) readPin(f Files, p instance.Paths, in *spec.Instance, obs *Observation) *spec.Manifest {
	if in == nil {
		return nil
	}
	raw, err := f.ReadFile(p.ManifestLock)
	if err != nil {
		if !errors.Is(err, fs.ErrNotExist) {
			obs.Problems = append(obs.Problems, Problem{Source: "pin", Path: p.ManifestLock, Detail: err.Error()})
		}
		return nil
	}
	obs.Pin.Present = true
	obs.Pin.Revision = in.Spec.Manifest.Revision
	obs.Pin.SHA256 = in.Spec.Manifest.SHA256
	m, _, err := spec.ValidateBytes(p.ManifestLock, raw)
	if err != nil {
		obs.Pin.Reason = err.Error()
		return nil
	}
	if err := in.Spec.Manifest.Verify(m); err != nil {
		obs.Pin.Reason = err.Error()
		return m
	}
	obs.Pin.OK = true
	return m
}

func (o *Observer) readDropIn(f Files, name string, obs *Observation) {
	p := instance.DropInPath(name)
	raw, err := f.ReadFile(p)
	if err != nil {
		if !errors.Is(err, fs.ErrNotExist) {
			obs.Problems = append(obs.Problems, Problem{Source: "dropin", Path: p, Detail: err.Error()})
		}
	} else {
		obs.DropInPresent = true
		obs.DropIn = ParseDropInHeader(strings.NewReader(string(raw)))
		if !obs.DropIn.Generated {
			// A file at gvm's own path that gvm did not write governs a live
			// server and must never be silently overwritten (section 20's
			// INST-014 is the reporting half).
			obs.Problems = append(obs.Problems, Problem{
				Source: "dropin", Path: p,
				Detail: "does not carry the generated header; gvm did not write it",
			})
		}
	}
	if _, err := f.Stat(path.Join(path.Dir(p), localDropIn)); err == nil {
		obs.LocalDropIn = true
	}
}

func (o *Observer) readUnit(ctx context.Context, name string, obs *Observation) {
	if o.Units == nil {
		return
	}
	st, err := o.Units.State(ctx, instance.UnitName(name))
	if err != nil {
		obs.Problems = append(obs.Problems, Problem{Source: "systemd", Detail: err.Error()})
		return
	}
	obs.UnitChecked = true
	obs.Unit = st
}

func (o *Observer) readStatus(f Files, p instance.Paths, obs *Observation) {
	fi, err := f.Stat(p.StatusJSON)
	if err != nil {
		if !errors.Is(err, fs.ErrNotExist) {
			obs.Problems = append(obs.Problems, Problem{Source: "status", Path: p.StatusJSON, Detail: err.Error()})
		}
		return
	}
	obs.StatusModTime = fi.ModTime()
	raw, err := f.ReadFile(p.StatusJSON)
	if err != nil {
		obs.Problems = append(obs.Problems, Problem{Source: "status", Path: p.StatusJSON, Detail: err.Error()})
		return
	}
	var st runner.Status
	if err := json.Unmarshal(raw, &st); err != nil {
		obs.Problems = append(obs.Problems, Problem{Source: "status", Path: p.StatusJSON, Detail: err.Error()})
		return
	}
	obs.Status = &st
}

func (o *Observer) readMarkers(f Files, p instance.Paths, obs *Observation) {
	if raw, err := f.ReadFile(p.Hold); err == nil {
		obs.Hold = true
		obs.HoldReason = firstLine(raw)
	} else if !errors.Is(err, fs.ErrNotExist) {
		obs.Problems = append(obs.Problems, Problem{Source: "hold", Path: p.Hold, Detail: err.Error()})
	}
	if _, err := f.Stat(p.FreezeLease); err == nil {
		obs.FreezeLease = true
	}
	if _, err := f.Stat(p.BlockedMods); err == nil {
		obs.BlockedMods = true
	}
}

// readInstalled looks for the provider's declared sentinel.
//
// The sentinel is the manifest's answer to "is it installed?" and it is
// required for every provider that installs anything (section 8.6). Using it
// rather than "is the install directory non-empty" is what makes the answer
// survive a half-finished SteamCMD run: a directory with 40 GB of a 65 GB
// download in it is not empty and is not installed.
func (o *Observer) readInstalled(f Files, in *spec.Instance, m *spec.Manifest, obs *Observation) {
	if in == nil || m == nil {
		return
	}
	s, ok := sentinelOf(m)
	if !ok || s.Path == "" {
		// An adopted or provider-less instance declares no sentinel. Unknown
		// is the honest answer and provisioning is not reported for it.
		return
	}
	full := path.Join(in.Spec.Paths.Install, s.Path)
	fi, err := f.Stat(full)
	switch {
	case errors.Is(err, fs.ErrNotExist):
		obs.Installed = No
	case err != nil:
		obs.Problems = append(obs.Problems, Problem{Source: "install", Path: full, Detail: err.Error()})
	case s.MinBytes > 0 && fi.Size() < s.MinBytes:
		// A zero-length sentinel is what a truncated extract leaves behind.
		obs.Installed = No
		obs.Problems = append(obs.Problems, Problem{
			Source: "install", Path: full,
			Detail: "sentinel is " + strconv.FormatInt(fi.Size(), 10) + " bytes, manifest requires at least " +
				strconv.FormatInt(s.MinBytes, 10),
		})
	default:
		obs.Installed = Yes
	}
}

func (o *Observer) readLease(f Files, name string, obs *Observation) {
	p := LeasePath(name)
	raw, err := f.ReadFile(p)
	if err != nil {
		if !errors.Is(err, fs.ErrNotExist) {
			// A lease that exists and cannot be read is treated as a lease.
			obs.LeaseUnreadable = true
			obs.Problems = append(obs.Problems, Problem{Source: "lease", Path: p, Detail: err.Error()})
		}
		return
	}
	// Liveness is read with the version-independent reader so that a lease a
	// newer gvm wrote -- after an upgrade bumped LeaseProto -- is classified
	// live or stale, not reported unreadable and then cleared out from under a
	// running job (U17, the N-1 skew rule). "Unreadable" is reserved for a
	// document that will not decode as JSON at all.
	live, err := ParseLeaseLiveness(strings.NewReader(string(raw)))
	if err != nil {
		obs.LeaseUnreadable = true
		obs.Problems = append(obs.Problems, Problem{Source: "lease", Path: p, Detail: err.Error()})
		return
	}
	// Prefer the strict, typed lease when this build understands it -- it
	// carries the validated Kind and the Reason an operator reads -- and fall
	// back to the liveness view for a lease from a future version.
	obs.Lease = live.Lease()
	if l, perr := ParseLease(strings.NewReader(string(raw))); perr == nil {
		obs.Lease = l
	}

	alive := Unknown
	if o.Alive != nil && live.PID > 0 {
		alive = o.Alive(live.PID)
	}
	obs.LeaseState = live.Classify(obs.Now, o.BootID, alive)
}

// ParseDropInHeader reads the provenance block of a generated drop-in.
//
// It is a pure function over a reader and it never fails: a file that is not
// one of gvm's comes back with Generated false, which is a fact the caller
// needs rather than an error it has to handle. Section 7.4 fixes the format,
// and the header is the DB-free source of instances.applied_sha256.
func ParseDropInHeader(r io.Reader) DropInHeader {
	var h DropInHeader
	sc := bufio.NewScanner(io.LimitReader(r, 64<<10))
	for sc.Scan() {
		line := strings.TrimRight(sc.Text(), "\r")
		if !strings.HasPrefix(line, "#") {
			// The header is the comment block at the top. A `# ` line further
			// down explains a directive and is not provenance.
			break
		}
		if line == generatedMarker {
			h.Generated = true
			continue
		}
		body := strings.TrimSpace(strings.TrimPrefix(line, "#"))
		switch {
		case strings.HasPrefix(body, "source "):
			h.SpecPath = strings.TrimSpace(strings.TrimPrefix(body, "source "))
		case strings.HasPrefix(body, "spec sha256 "):
			h.SpecSHA256 = strings.TrimSpace(strings.TrimPrefix(body, "spec sha256 "))
		case strings.HasPrefix(body, "manifest "):
			parseManifestLine(strings.TrimSpace(strings.TrimPrefix(body, "manifest ")), &h)
		case strings.HasPrefix(body, "rendered "):
			parseRenderedLine(strings.TrimSpace(strings.TrimPrefix(body, "rendered ")), &h)
		}
	}
	return h
}

// parseManifestLine reads `projectzomboid rev 7 sha256:1b40c9de (origin: shipped)`.
func parseManifestLine(s string, h *DropInHeader) {
	fields := strings.Fields(s)
	for i, f := range fields {
		switch {
		case i == 0:
			h.Game = f
		case f == "rev" && i+1 < len(fields):
			h.Revision, _ = strconv.Atoi(fields[i+1])
		case strings.HasPrefix(f, "sha256:"):
			h.ManifestSHA = strings.TrimPrefix(f, "sha256:")
		case f == "(origin:" && i+1 < len(fields):
			h.Origin = strings.TrimSuffix(fields[i+1], ")")
		}
	}
}

// parseRenderedLine reads `2026-09-04T18:22:11Z by gvm 0.1.0`.
func parseRenderedLine(s string, h *DropInHeader) {
	fields := strings.Fields(s)
	if len(fields) > 0 {
		if t, err := time.Parse(time.RFC3339, fields[0]); err == nil {
			h.Rendered = t
		}
	}
	if n := len(fields); n >= 2 {
		h.Version = fields[n-1]
	}
}

// sentinelOf is the manifest's install sentinel, whichever provider declares
// it. A provider with none (adopted, none) returns false rather than an empty
// Sentinel, so a caller cannot mistake "declares nothing" for "declares a
// path of ”".
func sentinelOf(m *spec.Manifest) (spec.Sentinel, bool) {
	p := m.Spec.Provider
	switch {
	case p.SteamCMD != nil:
		return p.SteamCMD.Sentinel, true
	case p.Minecraft != nil:
		return p.Minecraft.Sentinel, true
	}
	return spec.Sentinel{}, false
}

// sha256Hex is the instance spec's digest, taken over the bytes on disk.
//
// It is computed here rather than read from anywhere, because the whole value
// of the number is that it is the file's, so `sha256sum
// /etc/gvm/instances/pz-main.yaml` and the drop-in's header line agree.
func sha256Hex(b []byte) string {
	sum := sha256.Sum256(b)
	return hex.EncodeToString(sum[:])
}

func firstLine(b []byte) string {
	s := string(b)
	if i := strings.IndexAny(s, "\r\n"); i >= 0 {
		s = s[:i]
	}
	return strings.TrimSpace(s)
}
