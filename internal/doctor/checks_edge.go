// Package doctor implements gvm doctor checks — read-only invariant assertions.
// Unlike internal/lifecycle, this package may read files and run programs.
package doctor

import (
	"bufio"
	"bytes"
	"context"
	"fmt"
	"os"
	"os/exec"
	"strings"

	"github.com/S95F/gameVPSmanager/internal/lifecycle"
	"github.com/S95F/gameVPSmanager/internal/spec"
)

// EdgeChecks returns EDGE-* checks given the host config.
// Checks that require a running Caddy process return Skip gracefully.
func EdgeChecks(host *spec.HostConfig) []lifecycle.DoctorCheck {
	return []lifecycle.DoctorCheck{
		edgeCheckCaddyVersion(host),
		{
			ID:      "EDGE-003",
			Summary: "/etc/caddy/Caddyfile (dpkg conffile) is not modified by gvm",
			Run:     checkEtcCaddyfileUnmodified(host),
		},
		{
			ID:      "EDGE-004",
			Summary: "Caddy admin API is on a unix socket, not localhost:2019 (D-36)",
			Run:     checkCaddyAdminSocket(host),
		},
		{
			ID:      "EDGE-005",
			Summary: "no listener on 2019/tcp",
			Run:     checkNoListener2019,
		},
		{
			ID:      "EDGE-008",
			Summary: "encode Content-Type matcher does not include text/*",
			Run:     checkEncodeNoTextStar(host),
		},
		{
			ID:      "EDGE-009",
			Summary: "/stream/* sets flush_interval -1 and stream_close_delay 5m",
			Run:     checkStreamFlushInterval(host),
		},
	}
}

func edgeCheckCaddyVersion(host *spec.HostConfig) lifecycle.DoctorCheck {
	return lifecycle.DoctorCheck{
		ID:      "EDGE-001",
		Summary: "caddy version meets minimum requirement",
		Run: func(ctx context.Context, _ lifecycle.CheckEnv) lifecycle.CheckFinding {
			minVer := host.Spec.Edge.Caddy.MinVersion
			if minVer == "" {
				minVer = "2.11.1"
			}
			out, err := exec.CommandContext(ctx, "caddy", "version").Output()
			if err != nil {
				return lifecycle.CheckFinding{
					ID:       "EDGE-001",
					Severity: lifecycle.CheckSkip,
					Message:  "caddy not found in PATH",
					Fix:      "apt install caddy (or use gvm bundled build)",
				}
			}
			ver := strings.TrimSpace(string(out))
			if !meetsMinVersion(ver, minVer) {
				return lifecycle.CheckFinding{
					ID:       "EDGE-001",
					Severity: lifecycle.CheckProblem,
					Message:  fmt.Sprintf("caddy %s does not meet minimum %s", ver, minVer),
					Fix:      fmt.Sprintf("upgrade caddy to >= %s", minVer),
				}
			}
			return lifecycle.CheckFinding{
				ID:       "EDGE-001",
				Severity: lifecycle.CheckOK,
				Message:  fmt.Sprintf("caddy %s (>= %s required)", ver, minVer),
			}
		},
	}
}

func checkEtcCaddyfileUnmodified(_ *spec.HostConfig) func(context.Context, lifecycle.CheckEnv) lifecycle.CheckFinding {
	return func(_ context.Context, _ lifecycle.CheckEnv) lifecycle.CheckFinding {
		const etcCaddy = "/etc/caddy/Caddyfile"
		b, err := os.ReadFile(etcCaddy)
		if err != nil {
			if os.IsNotExist(err) {
				return lifecycle.CheckFinding{ID: "EDGE-003", Severity: lifecycle.CheckSkip, Message: etcCaddy + " does not exist"}
			}
			return lifecycle.CheckFinding{ID: "EDGE-003", Severity: lifecycle.CheckProblem, Message: err.Error()}
		}
		if bytes.Contains(b, []byte("Generated by gvm")) {
			return lifecycle.CheckFinding{
				ID:       "EDGE-003",
				Severity: lifecycle.CheckProblem,
				Message:  "/etc/caddy/Caddyfile contains gvm header — gvm must not own this file (D-37)",
				Fix:      "restore: dpkg --force-confmiss -i caddy",
			}
		}
		return lifecycle.CheckFinding{
			ID:       "EDGE-003",
			Severity: lifecycle.CheckOK,
			Message:  "/etc/caddy/Caddyfile (dpkg conffile) unmodified by gvm",
		}
	}
}

func checkCaddyAdminSocket(host *spec.HostConfig) func(context.Context, lifecycle.CheckEnv) lifecycle.CheckFinding {
	return func(_ context.Context, _ lifecycle.CheckEnv) lifecycle.CheckFinding {
		admin := host.Spec.Edge.Caddy.Admin
		if !strings.HasPrefix(admin, "unix/") {
			return lifecycle.CheckFinding{
				ID:       "EDGE-004",
				Severity: lifecycle.CheckProblem,
				Message:  fmt.Sprintf("caddy.admin %q is not a unix socket (D-36)", admin),
				Fix:      "set spec.edge.caddy.admin to unix//run/caddy/admin.sock",
			}
		}
		return lifecycle.CheckFinding{
			ID:       "EDGE-004",
			Severity: lifecycle.CheckOK,
			Message:  fmt.Sprintf("admin API on %s", admin),
		}
	}
}

func checkNoListener2019(_ context.Context, _ lifecycle.CheckEnv) lifecycle.CheckFinding {
	b, err := os.ReadFile("/proc/net/tcp")
	if err != nil {
		return lifecycle.CheckFinding{ID: "EDGE-005", Severity: lifecycle.CheckSkip, Message: "cannot read /proc/net/tcp"}
	}
	if procNetHasPort(b, 2019) {
		return lifecycle.CheckFinding{
			ID:       "EDGE-005",
			Severity: lifecycle.CheckProblem,
			Message:  "something is listening on 2019/tcp (Caddy remote admin must be disabled) (D-36)",
			Fix:      "disable Caddy remote admin API",
		}
	}
	return lifecycle.CheckFinding{ID: "EDGE-005", Severity: lifecycle.CheckOK, Message: "no listener on 2019/tcp"}
}

func checkEncodeNoTextStar(host *spec.HostConfig) func(context.Context, lifecycle.CheckEnv) lifecycle.CheckFinding {
	return func(_ context.Context, _ lifecycle.CheckEnv) lifecycle.CheckFinding {
		configPath := host.Spec.Edge.Caddy.ConfigPath
		if configPath == "" {
			return lifecycle.CheckFinding{ID: "EDGE-008", Severity: lifecycle.CheckSkip, Message: "no caddy config path configured"}
		}
		b, err := os.ReadFile(configPath)
		if err != nil {
			return lifecycle.CheckFinding{ID: "EDGE-008", Severity: lifecycle.CheckSkip, Message: "config not found: " + configPath}
		}
		if containsEncodeTextMatch(string(b)) {
			return lifecycle.CheckFinding{
				ID:       "EDGE-008",
				Severity: lifecycle.CheckProblem,
				Message:  "encode block matches text/* (breaks SSE on live console)",
				Fix:      "run: gvm caddy render",
			}
		}
		return lifecycle.CheckFinding{ID: "EDGE-008", Severity: lifecycle.CheckOK, Message: "encode Content-Type matcher does not include text/*"}
	}
}

func checkStreamFlushInterval(host *spec.HostConfig) func(context.Context, lifecycle.CheckEnv) lifecycle.CheckFinding {
	return func(_ context.Context, _ lifecycle.CheckEnv) lifecycle.CheckFinding {
		configPath := host.Spec.Edge.Caddy.ConfigPath
		if configPath == "" {
			return lifecycle.CheckFinding{ID: "EDGE-009", Severity: lifecycle.CheckSkip, Message: "no caddy config path configured"}
		}
		b, err := os.ReadFile(configPath)
		if err != nil {
			return lifecycle.CheckFinding{ID: "EDGE-009", Severity: lifecycle.CheckSkip, Message: "config not found: " + configPath}
		}
		content := string(b)
		if !strings.Contains(content, "flush_interval -1") {
			return lifecycle.CheckFinding{
				ID:       "EDGE-009",
				Severity: lifecycle.CheckProblem,
				Message:  "/stream/* routes missing flush_interval -1 (SSE will buffer)",
				Fix:      "run: gvm caddy render",
			}
		}
		if !strings.Contains(content, "stream_close_delay 5m") {
			return lifecycle.CheckFinding{
				ID:       "EDGE-009",
				Severity: lifecycle.CheckWarning,
				Message:  "/stream/* routes missing stream_close_delay 5m",
				Fix:      "run: gvm caddy render",
			}
		}
		return lifecycle.CheckFinding{ID: "EDGE-009", Severity: lifecycle.CheckOK, Message: "/stream/* sets flush_interval -1 and stream_close_delay 5m"}
	}
}

func meetsMinVersion(ver, minVer string) bool {
	fields := strings.Fields(ver)
	if len(fields) == 0 {
		return false
	}
	v := strings.TrimPrefix(fields[0], "v")
	min := strings.TrimPrefix(minVer, "v")
	return semverGE(v, min)
}

func semverGE(a, b string) bool {
	ap := strings.SplitN(a, ".", 3)
	bp := strings.SplitN(b, ".", 3)
	for len(ap) < 3 {
		ap = append(ap, "0")
	}
	for len(bp) < 3 {
		bp = append(bp, "0")
	}
	for i := 0; i < 3; i++ {
		ai := atoi0(ap[i])
		bi := atoi0(bp[i])
		if ai > bi {
			return true
		}
		if ai < bi {
			return false
		}
	}
	return true
}

func atoi0(s string) int {
	n := 0
	for _, c := range s {
		if c < '0' || c > '9' {
			break
		}
		n = n*10 + int(c-'0')
	}
	return n
}

func procNetHasPort(data []byte, port int) bool {
	hexPort := fmt.Sprintf("%04X", port)
	sc := bufio.NewScanner(bytes.NewReader(data))
	for sc.Scan() {
		line := sc.Text()
		fields := strings.Fields(line)
		if len(fields) < 4 {
			continue
		}
		local := fields[1]
		state := fields[3]
		if state != "0A" {
			continue
		}
		if idx := strings.LastIndex(local, ":"); idx >= 0 {
			if strings.EqualFold(local[idx+1:], hexPort) {
				return true
			}
		}
	}
	return false
}

func containsEncodeTextMatch(content string) bool {
	inEncode := false
	depth := 0
	sc := bufio.NewScanner(strings.NewReader(content))
	for sc.Scan() {
		line := strings.TrimSpace(sc.Text())
		if strings.HasPrefix(line, "encode") && !inEncode {
			inEncode = true
		}
		if inEncode {
			depth += strings.Count(line, "{") - strings.Count(line, "}")
			if strings.Contains(line, "text/*") || strings.Contains(line, "text/event-stream") {
				return true
			}
			if depth <= 0 {
				inEncode = false
			}
		}
	}
	return false
}
