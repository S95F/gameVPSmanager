// mc.accept_eula, mc.select_jdk, mc.write_properties, mc.gamerule_fallback
// are the four Minecraft hooks that complete the provider installation.
//
// They run after Provider.Apply has unpacked the server JAR and written
// .gvm-java-major. Each hook is idempotent: running it twice is the same as
// running it once.

// mcAcceptEULA is mc.accept_eula.
//
// Minecraft refuses to start without eula.txt containing "eula=true". This
// hook writes the file on first install. It is the only place gvm touches a
// Mojang terms file; operators may pre-create it themselves.
type mcAcceptEULA struct{}

func (mcAcceptEULA) Name() string    { return "mc.accept_eula" }
func (mcAcceptEULA) Phases() []Phase { return []Phase{PhasePostInstall} }
func (mcAcceptEULA) Doc() string {
	return "Writes eula.txt with eula=true in the data directory, which Minecraft requires " +
		"before it will start. Never overwrites an existing file. Operators who wish to use a " +
		"pre-existing eula.txt may create it before the first `gvm update`."
}

const eulaContent = "# Generated by gvm on first install.\n# https://aka.ms/MinecraftEULA\neula=true\n"
const eulaFile = "eula.txt"

func (mcAcceptEULA) Run(_ context.Context, h *Ctx) error {
	fsys, err := h.fsOf()
	if err != nil {
		return err
	}
	if _, err := fsys.Stat(RootData, eulaFile); err == nil {
		h.Note("%s already exists; not overwriting", eulaFile)
		return nil
	} else if !errors.Is(err, fs.ErrNotExist) {
		return fmt.Errorf("mc.accept_eula: stat %s: %w", eulaFile, err)
	}
	if err := fsys.WriteFile(RootData, eulaFile, []byte(eulaContent), 0o640); err != nil {
		return fmt.Errorf("mc.accept_eula: write %s: %w", eulaFile, err)
	}
	h.Note("wrote %s (eula=true)", eulaFile)
	return nil
}

// mcSelectJDK is mc.select_jdk.
//
// The Minecraft provider writes .gvm-java-major to the install directory
// during Apply; this hook reads it and creates (or updates) a symlink
// gvm-jre → the matching JVM home. The runtime exec is ./gvm-jre/bin/java,
// which pins the JVM to the instance without ever touching update-alternatives
// or any system-wide state.
type mcSelectJDK struct{}

func (mcSelectJDK) Name() string    { return "mc.select_jdk" }
func (mcSelectJDK) Phases() []Phase { return []Phase{PhasePreStart} }
func (mcSelectJDK) Doc() string {
	return "Reads .gvm-java-major from the install directory and creates a gvm-jre symlink " +
		"that points at the matching system JVM. The manifest exec uses ./gvm-jre/bin/java so " +
		"the JVM is pinned per-instance. update-alternatives is never used."
}

// jdkCandidates returns JVM home directories for the given major version in
// preference order. These are the well-known install paths on Debian/Ubuntu/RHEL.
// Directories are tested with os.Stat rather than by running java -version
// (spawning a process is forbidden by contract rule 1).
func jdkCandidates(major int) []string {
	m := strconv.Itoa(major)
	return []string{
		"/usr/lib/jvm/java-" + m + "-openjdk-amd64",
		"/usr/lib/jvm/java-" + m + "-openjdk",
		"/usr/lib/jvm/temurin-" + m,
		"/usr/lib/jvm/java-" + m + "-temurin-amd64",
		"/usr/lib/jvm/java-" + m,
		"/usr/local/lib/jvm/java-" + m,
	}
}

// gvmJavaMajorFile is the sentinel written by the Minecraft provider.
const gvmJavaMajorFile = ".gvm-java-major"

// gvmJRELink is the symlink name created in the install directory.
const gvmJRELink = "gvm-jre"

func (mcSelectJDK) Run(_ context.Context, h *Ctx) error {
	fsys, err := h.fsOf()
	if err != nil {
		return err
	}
	if !h.Paths.Install.Valid() {
		return fmt.Errorf("mc.select_jdk: no install path")
	}
	installDir := h.Paths.Install.Path()

	// Read the required Java major version from the install directory.
	majorBytes, err := fsys.ReadFile(RootInstall, gvmJavaMajorFile)
	if err != nil {
		if errors.Is(err, fs.ErrNotExist) {
			h.Problem("%s not found in install directory; Java symlink not created. "+
				"Run `gvm update <name> --repair` to re-create it.", gvmJavaMajorFile)
			return nil
		}
		return fmt.Errorf("mc.select_jdk: read %s: %w", gvmJavaMajorFile, err)
	}
	major, err := strconv.Atoi(strings.TrimSpace(string(majorBytes)))
	if err != nil || major < 8 {
		return fmt.Errorf("mc.select_jdk: invalid Java major version in %s: %q",
			gvmJavaMajorFile, strings.TrimSpace(string(majorBytes)))
	}

	// Find the first available JVM directory.
	var jvmHome string
	for _, cand := range jdkCandidates(major) {
		if fi, err := os.Stat(cand); err == nil && fi.IsDir() {
			jvmHome = cand
			break
		}
	}
	if jvmHome == "" {
		h.Problem("no Java %d JVM found; install openjdk-%d-jre-headless and re-run "+
			"`gvm start <name>`", major, major)
		return nil
	}

	linkPath := filepath.Join(installDir, gvmJRELink)

	// Idempotent: if the symlink already points at the right target, do nothing.
	if target, err := os.Readlink(linkPath); err == nil {
		if target == jvmHome {
			h.Note("%s already points at %s", gvmJRELink, jvmHome)
			return nil
		}
		// Target changed; remove the stale link and re-create.
		if err := h.links().Remove(linkPath); err != nil {
			return fmt.Errorf("mc.select_jdk: remove stale %s: %w", gvmJRELink, err)
		}
	}

	if err := h.links().Symlink(jvmHome, linkPath); err != nil {
		return fmt.Errorf("mc.select_jdk: symlink %s → %s: %w", gvmJRELink, jvmHome, err)
	}
	h.Note("linked %s → %s (Java %d)", gvmJRELink, jvmHome, major)
	return nil
}

// mcWriteProperties is mc.write_properties.
//
// Minecraft generates server.properties on first start, but the values it
// generates (a random level-seed, no password, default difficulty) are not
// what operators want. This hook pre-creates the file from manifest vars so
// the first start already has the right config.
type mcWriteProperties struct{}

func (mcWriteProperties) Name() string    { return "mc.write_properties" }
func (mcWriteProperties) Phases() []Phase { return []Phase{PhasePostInstall} }
func (mcWriteProperties) Doc() string {
	return "Opens the manifest's server.properties config file declaration and writes it " +
		"with the standard Minecraft property format on first install. Never overwrites an " +
		"existing file, because the operator may have tuned it and Minecraft writes it back " +
		"on shutdown."
}

const serverPropertiesName = "server.properties"

func (mcWriteProperties) Run(_ context.Context, h *Ctx) error {
	if h.Config == nil {
		h.Note("no Config accessor; mc.write_properties skipped")
		return nil
	}
	doc, commit, err := h.Config(serverPropertiesName)
	if err != nil {
		if errors.Is(err, ErrConfig) {
			h.Note("manifest declares no config file %q; mc.write_properties skipped",
				serverPropertiesName)
			return nil
		}
		return fmt.Errorf("mc.write_properties: %w", err)
	}
	if doc == nil {
		h.Note("server.properties already exists; not rewriting")
		return nil
	}
	if err := commit(); err != nil {
		return fmt.Errorf("mc.write_properties: commit: %w", err)
	}
	h.Note("wrote server.properties from manifest vars")
	return nil
}

// mcGameruleFallback is mc.gamerule_fallback.
//
// If the world directory does not yet exist (first install), this hook writes
// a pending marker so a future operator knows gamerule defaults have not yet
// been applied. Running gamerules requires a live server command, which is not
// available during post_install; the actual application is deferred.
type mcGameruleFallback struct{}

func (mcGameruleFallback) Name() string    { return "mc.gamerule_fallback" }
func (mcGameruleFallback) Phases() []Phase { return []Phase{PhasePostInstall} }
func (mcGameruleFallback) Doc() string {
	return "Checks whether a world directory exists. If not (first install), writes a " +
		".gvm-gamerule-pending marker in the data directory so the operator knows gamerules " +
		"have not yet been applied. Skipped on repair or adopted instances where a world " +
		"already exists."
}

const defaultLevelName = "world"
const gamerulePendingFile = ".gvm-gamerule-pending"
const gamerulePendingContent = "# gvm: gamerule_fallback pending first world generation\n"

func (mcGameruleFallback) Run(_ context.Context, h *Ctx) error {
	fsys, err := h.fsOf()
	if err != nil {
		return err
	}

	// If the world already exists, skip silently.
	if _, err := fsys.Stat(RootData, defaultLevelName); err == nil {
		h.Note("world directory %q already exists; gamerule fallback skipped", defaultLevelName)
		return nil
	} else if !errors.Is(err, fs.ErrNotExist) {
		return fmt.Errorf("mc.gamerule_fallback: stat world: %w", err)
	}

	// Write a pending marker if not already there.
	if _, err := fsys.Stat(RootData, gamerulePendingFile); err == nil {
		return nil
	}
	if err := fsys.WriteFile(RootData, gamerulePendingFile, []byte(gamerulePendingContent), 0o640); err != nil {
		return fmt.Errorf("mc.gamerule_fallback: write marker: %w", err)
	}
	h.Note("wrote %s (world not yet generated)", gamerulePendingFile)
	return nil
}
