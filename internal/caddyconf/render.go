// Package caddyconf renders the Caddy configuration gvm owns. gvm NEVER
// touches /etc/caddy/Caddyfile (D-37): it writes only the file at
// spec.caddy.config_path, which the system Caddyfile includes — or, in
// caddy_snippet mode, a bare site block for a Caddy somebody else runs.
//
// Three golden rules:
//
//  1. encode's matcher must never include text/* — it matches text/event-stream
//     and breaks SSE on the dashboard's live-console feed (D-38).
//
//  2. The reserved /stream/ and /api/v1/stream/ prefixes get their own handle
//     blocks with flush_interval -1 and stream_close_delay 5m, so the
//     server-sent event stream is flushed immediately and survives a reload.
//
//  3. Caddy's admin API listens on a unix socket, never localhost:2019 (D-36).
//     An SSRF through gvm-web could otherwise POST to the admin API and replace
//     the entire proxy configuration.
package caddyconf

import (
	"fmt"
	"io"
	"strings"

	"github.com/S95F/gameVPSmanager/internal/edge"
	"github.com/S95F/gameVPSmanager/internal/spec"
)

// Render writes the Caddy config for plan to w.
//
//   - caddy_managed: the full Caddyfile (global options + one site block)
//   - caddy_snippet: the site block only, for a Caddy the operator runs —
//     drop it into a directory the system Caddyfile already imports (e.g. a
//     sites.d managed alongside serverGitUpdater snippets) and reload
//   - none: global options only (admin socket pinned even with no web edge)
//   - proxy_external: an error — gvm writes nothing for a foreign proxy
func Render(w io.Writer, host *spec.HostConfig, plan *edge.Plan) error {
	var b strings.Builder

	switch plan.Mode {
	case "proxy_external":
		return fmt.Errorf("caddyconf: gvm renders no Caddy config in proxy_external mode; " +
			"the operator's proxy owns its own config (§17.3)")

	case "none":
		if err := writeHeaderAndGlobal(&b, host, plan); err != nil {
			return err
		}

	case "caddy_managed":
		if err := writeHeaderAndGlobal(&b, host, plan); err != nil {
			return err
		}
		b.WriteString("\n")
		writeSite(&b, plan, host.Spec.Edge.Caddy.LogPath)

	case "caddy_snippet":
		writeSnippetHeader(&b)
		writeSite(&b, plan, "")

	default:
		return fmt.Errorf("caddyconf: cannot render edge mode %q", plan.Mode)
	}

	_, err := io.WriteString(w, b.String())
	return err
}

// writeHeaderAndGlobal emits the ownership banner and the global options
// block, validating the admin address (D-36).
func writeHeaderAndGlobal(b *strings.Builder, host *spec.HostConfig, plan *edge.Plan) error {
	caddy := host.Spec.Edge.Caddy

	adminSock := strings.TrimPrefix(caddy.Admin, "unix/")
	if adminSock == "" || !strings.HasPrefix(adminSock, "/") {
		// e.g. "localhost:2019" — not a unix socket.
		return fmt.Errorf("caddyconf: caddy.admin %q is not a unix socket path (D-36)", caddy.Admin)
	}

	fmt.Fprintf(b, "# Generated by gvm. Do NOT edit this file directly.\n")
	fmt.Fprintf(b, "# gvm owns: %s\n", caddy.ConfigPath)
	fmt.Fprintf(b, "# gvm NEVER writes /etc/caddy/Caddyfile (D-37).\n\n")

	b.WriteString("{\n")
	// |0660: root and the caddy group may use the admin socket; nobody else.
	fmt.Fprintf(b, "\tadmin unix/%s|0660 {\n", adminSock)
	b.WriteString("\t\tenforce_origin\n")
	b.WriteString("\t}\n")
	if plan.Email != "" && (plan.TLS == edge.TLSAcmeHTTP || plan.TLS == edge.TLSAcmeDNS) {
		fmt.Fprintf(b, "\temail %s\n", plan.Email)
	}
	if plan.Mode == "caddy_managed" && !plan.HTTPRedirect {
		b.WriteString("\tauto_https disable_redirects\n")
	}
	b.WriteString("\tservers {\n")
	b.WriteString("\t\ttimeouts {\n")
	b.WriteString("\t\t\tread_header 10s\n")
	b.WriteString("\t\t\tidle 10m\n")
	b.WriteString("\t\t}\n")
	if plan.Mode == "caddy_managed" && !plan.HTTP3 {
		// http3: false => h1 h2 only, and 443/udp is NOT opened (§17.1).
		b.WriteString("\t\tprotocols h1 h2\n")
	} else {
		b.WriteString("\t\tprotocols h1 h2 h3\n")
	}
	b.WriteString("\t}\n")
	b.WriteString("}\n")
	return nil
}

// writeSnippetHeader banners the snippet-mode output: gvm owns the file, the
// operator owns Caddy.
func writeSnippetHeader(b *strings.Builder) {
	b.WriteString("# Managed by gvm (edge.mode: caddy_snippet). Do NOT edit this file directly.\n")
	b.WriteString("# gvm never touches caddy.service in this mode. Import this site from the\n")
	b.WriteString("# system Caddyfile:\n")
	b.WriteString("#     import /etc/gvm/caddy/gvm.caddyfile\n")
	b.WriteString("# or drop it into a sites directory the Caddyfile already imports\n")
	b.WriteString("# (e.g. /etc/caddy/sites.d with `import sites.d/*.caddy`).\n\n")
}

// writeSite emits the ONE vhost (web-dashboard-11): all per-instance routing
// happens inside gvm-web at /i/{name}/…, which is what keeps a Caddy reload a
// rare, auditable event. logPath == "" omits the log block (snippet mode: the
// operator's Caddy owns logging).
func writeSite(b *strings.Builder, plan *edge.Plan, logPath string) {
	up := upstream(plan)

	fmt.Fprintf(b, "%s {\n", plan.Site)

	switch plan.TLS {
	case edge.TLSInternal:
		b.WriteString("\ttls internal\n\n")
	case edge.TLSAcmeDNS:
		// The credential rides as {env.<VAR>} so the secret never lands in
		// the Caddyfile; tls.dns_env names the variable.
		b.WriteString("\ttls {\n")
		if plan.DNSEnvVar != "" {
			fmt.Fprintf(b, "\t\tdns %s {env.%s}\n", plan.DNSProvider, plan.DNSEnvVar)
		} else {
			fmt.Fprintf(b, "\t\tdns %s\n", plan.DNSProvider)
		}
		b.WriteString("\t}\n\n")
	case edge.TLSAcmeHTTP, edge.TLSExternal:
		// acme_http: Caddy's automatic HTTPS needs no directive.
		// external: whoever terminates TLS owns its config.
	}

	b.WriteString("\t# text/* is NOT in this list on purpose: it matches text/event-stream,\n")
	b.WriteString("\t# and the live console must not depend on the encoder's flush behaviour\n")
	b.WriteString("\t# (D-38).\n")
	b.WriteString("\tencode zstd gzip {\n")
	b.WriteString("\t\tmatch {\n")
	b.WriteString("\t\t\theader Content-Type text/html*\n")
	b.WriteString("\t\t\theader Content-Type text/css*\n")
	b.WriteString("\t\t\theader Content-Type text/plain*\n")
	b.WriteString("\t\t\theader Content-Type application/json*\n")
	b.WriteString("\t\t\theader Content-Type application/javascript*\n")
	b.WriteString("\t\t\theader Content-Type image/svg+xml*\n")
	b.WriteString("\t\t}\n")
	b.WriteString("\t}\n\n")

	b.WriteString("\theader {\n")
	b.WriteString("\t\tX-Content-Type-Options nosniff\n")
	b.WriteString("\t\tReferrer-Policy strict-origin-when-cross-origin\n")
	b.WriteString("\t\tCross-Origin-Opener-Policy same-origin\n")
	if plan.HSTS {
		// Only ever emitted for a public DNS name with real TLS — a one-way
		// door per hostname (§17.1); ComputePlan enforces the conditions.
		b.WriteString("\t\tStrict-Transport-Security \"max-age=31536000\"\n")
	}
	b.WriteString("\t\t-Server\n")
	b.WriteString("\t}\n\n")

	b.WriteString("\t# /stream/ and /api/v1/stream/ are reserved by gvm for Server-Sent\n")
	b.WriteString("\t# Events and nothing else, so these matchers can never drift as the\n")
	b.WriteString("\t# app grows routes (D-38).\n")
	for _, prefix := range []string{"/stream/*", "/api/v1/stream/*"} {
		fmt.Fprintf(b, "\thandle %s {\n", prefix)
		fmt.Fprintf(b, "\t\treverse_proxy %s {\n", up)
		b.WriteString("\t\t\tflush_interval -1\n")
		// A config reload tears down streaming responses; 5m of grace keeps
		// every operator's console alive across an `apply`.
		b.WriteString("\t\t\tstream_close_delay 5m\n")
		b.WriteString("\t\t}\n")
		b.WriteString("\t}\n\n")
	}

	b.WriteString("\thandle {\n")
	fmt.Fprintf(b, "\t\treverse_proxy %s\n", up)
	b.WriteString("\t}\n")

	if logPath != "" {
		b.WriteString("\n\tlog {\n")
		fmt.Fprintf(b, "\t\toutput file %s {\n", logPath)
		b.WriteString("\t\t\troll_size 10MiB\n")
		b.WriteString("\t\t\troll_keep 5\n")
		b.WriteString("\t\t}\n")
		b.WriteString("\t\tformat json\n")
		b.WriteString("\t}\n")
	}

	b.WriteString("}\n")
}

// upstream renders the reverse_proxy target. The plan carries a bare socket
// path or host:port; the single unix/ prefix is added exactly once here —
// "unix/" + "/run/gvm/web/dashboard.sock" = "unix//run/gvm/web/dashboard.sock".
func upstream(plan *edge.Plan) string {
	if plan.Upstream.Network == "unix" {
		return "unix/" + plan.Upstream.Address
	}
	return plan.Upstream.Address
}
