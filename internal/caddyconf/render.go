// Package caddyconf renders and manages the Caddy configuration file that gvm
// owns. gvm NEVER touches /etc/caddy/Caddyfile (D-37): it writes only the
// file at spec.caddy.config_path, which is included by the system Caddyfile.
//
// Three golden rules:
//
//  1. encode's matcher must never include text/* — it matches text/event-stream
//     and breaks SSE on the dashboard's live-console feed.
//
//  2. /stream/* routes emit flush_interval -1 and stream_close_delay 5m so
//     the server-sent event stream is flushed immediately.
//
//  3. Caddy's admin API listens on a unix socket, never localhost:2019 (D-36).
//     An SSRF through gvm-web could otherwise POST to the admin API and replace
//     the entire proxy configuration.
package caddyconf

import (
	"fmt"
	"io"
	"strings"
	"text/template"

	"github.com/S95F/gameVPSmanager/internal/edge"
	"github.com/S95F/gameVPSmanager/internal/spec"
)

const caddyfileTemplate = `# Generated by gvm. Do NOT edit this file directly.
# gvm owns: {{ .ConfigPath }}
# gvm NEVER writes /etc/caddy/Caddyfile (D-37).

{
	admin unix/{{ .AdminSocket }}
	log {
		output file {{ .LogPath }}
		format json
	}
}

{{ if eq .Mode "caddy_managed" -}}
{{ range .Routes -}}
{{ .Host }} {
	{{ if eq .TLS "auto" -}}
	tls {{ if $.TLSEmail }}{{ $.TLSEmail }}{{ end }}
	{{ else if eq .TLS "internal" -}}
	tls internal
	{{ else if eq .TLS "external" -}}
	tls {{ $.TLSCert }} {{ $.TLSKey }}
	{{ end -}}

	{{ if .EnforceHTTPS -}}
	redir http://{{ .Host }}{uri} https://{{ .Host }}{uri} 308
	{{ end -}}

	# Compress non-streaming responses. Path-exclusion only.
	# Using a Content-Type matcher here breaks SSE (see D-36 comment in render.go).
	@compressible {
		not path /stream/*
	}
	encode @compressible gzip zstd

	# SSE / live-console streams: flush immediately.
	@stream path /stream/*
	handle @stream {
		reverse_proxy unix/{{ .Upstream }} {
			flush_interval -1
			stream_close_delay 5m
		}
	}

	reverse_proxy unix/{{ .Upstream }}
}

{{ end -}}
{{ end -}}
`

// RenderInput holds everything the template needs.
type RenderInput struct {
	ConfigPath  string
	AdminSocket string
	LogPath     string
	Mode        string
	Routes      []routeInput
	TLSEmail    string
	TLSCert     string
	TLSKey      string
}

type routeInput struct {
	Host         string
	Upstream     string
	TLS          string
	EnforceHTTPS bool
}

// Render writes a Caddyfile to w from the given host spec and edge plan.
func Render(w io.Writer, host *spec.HostConfig, plan *edge.Plan) error {
	caddy := host.Spec.Edge.Caddy

	adminSock := caddy.Admin
	// Strip the single "unix/" prefix. The template prepends "unix/" so the
	// output is "unix//path" (absolute) or "unix/path" (relative).
	// "unix//run/caddy/admin.sock" → strip "unix/" → "/run/caddy/admin.sock"
	adminSock = strings.TrimPrefix(adminSock, "unix/")
	if adminSock == "" {
		return fmt.Errorf("caddyconf: caddy.admin must be a unix socket path (D-36)")
	}
	if !strings.HasPrefix(adminSock, "/") {
		// e.g. "localhost:2019" — not a unix socket
		return fmt.Errorf("caddyconf: caddy.admin %q is not a unix socket path (D-36)", caddy.Admin)
	}

	inp := RenderInput{
		ConfigPath:  caddy.ConfigPath,
		AdminSocket: adminSock,
		LogPath:     caddy.LogPath,
		Mode:        plan.Mode,
		TLSEmail:    host.Spec.Edge.TLS.Email,
	}

	for _, r := range plan.Routes {
		inp.Routes = append(inp.Routes, routeInput{
			Host:         r.Host,
			Upstream:     r.Upstream,
			TLS:          string(r.TLS),
			EnforceHTTPS: r.EnforceHTTPS,
		})
	}

	tmpl, err := template.New("caddyfile").Parse(caddyfileTemplate)
	if err != nil {
		return fmt.Errorf("caddyconf: template parse: %w", err)
	}
	return tmpl.Execute(w, inp)
}
