package cli

import (
	"fmt"
	"strings"

	"github.com/S95F/gameVPSmanager/internal/avail"
)

// subGroupsForDocs is every verb that has a subcommand table, so the generated
// reference and a future validity test both read the one list the dispatch
// uses. A group added here appears in docs/cli-reference.md the day it is
// added; keeping it in step is a test, not a discipline.
func subGroupsForDocs() []subGroup {
	return []subGroup{
		userGroup(), tokenGroup(), secretGroup(), auditGroup(), dbGroup(), adoptGroup(),
	}
}

// GenerateCLIReference renders docs/cli-reference.md from the dispatch tables:
// the top-level commands grouped as the usage lists them, each with its
// availability, and the subcommand tables with theirs. It is the source for
// `make docs-cli`, and TestCLIReferenceIsUpToDate fails when the committed file
// no longer matches it (U16's CI diff) — so the reference cannot drift from the
// binary it documents.
func GenerateCLIReference() string {
	var b strings.Builder
	b.WriteString("# gvm CLI reference\n\n")
	b.WriteString("Generated by `make docs-cli` from the dispatch tables. Do not edit by hand;\n")
	b.WriteString("run `make docs-cli` after changing a command.\n\n")

	subByVerb := map[string]subGroup{}
	for _, g := range subGroupsForDocs() {
		subByVerb[g.Verb] = g
	}

	for _, grp := range groupOrder {
		var cmds []Command
		for _, c := range commands {
			if c.Group == grp.key && !c.Hidden {
				cmds = append(cmds, c)
			}
		}
		if len(cmds) == 0 {
			continue
		}
		fmt.Fprintf(&b, "## %s\n\n", grp.title)
		for _, c := range cmds {
			fmt.Fprintf(&b, "### gvm %s\n\n", c.Name)
			fmt.Fprintf(&b, "%s%s\n\n", c.Summary, availNote(c.Avail))
			if g, ok := subByVerb[c.Name]; ok {
				b.WriteString("Subcommands:\n\n")
				for _, s := range g.Subs {
					fmt.Fprintf(&b, "- `%s` — %s%s\n", s.Name, s.Summary, availNote(s.Avail))
				}
				b.WriteString("\n")
				writeExamples(&b, g.Subs)
			}
		}
	}
	return b.String()
}

// availNote renders a command's availability as a short parenthetical, or
// nothing when it just works.
func availNote(a avail.Availability) string {
	switch a.State {
	case avail.NotInBuild:
		if a.Why != "" {
			return " _(not in this build: " + a.Why + ")_"
		}
		return " _(not in this build)_"
	case avail.Partial:
		if a.Why != "" {
			return " _(partial: " + a.Why + ")_"
		}
		return " _(partial)_"
	}
	return ""
}

func writeExamples(b *strings.Builder, subs []subcmd) {
	var any bool
	for _, s := range subs {
		if len(s.Examples) > 0 {
			any = true
			break
		}
	}
	if !any {
		return
	}
	b.WriteString("Examples:\n\n```\n")
	for _, s := range subs {
		for _, ex := range s.Examples {
			b.WriteString(ex)
			b.WriteString("\n")
		}
	}
	b.WriteString("```\n\n")
}
