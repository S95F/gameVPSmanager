package gamecfg

import (
	"bytes"
	"errors"
	"fmt"
	"regexp"
	"strings"
)

// ErrKeyNotFound means the requested key does not exist in the document.
//
// Callers must treat this as "skip and warn", never as "add it". The server
// generates SandboxVars.lua from its own schema, and a key the file does not
// contain is a typo or a setting from a different game version. Inventing it
// produces a file the game silently ignores, so a typo would look like it
// worked and quietly do nothing.
var ErrKeyNotFound = errors.New("gamecfg: key not found")

// SandboxVars edits Project Zomboid's <servername>_SandboxVars.lua.
//
// The file is a Lua table literal, two levels deep:
//
//	SandboxVars = {
//	    Zombies = 4,
//	    ZombieConfig = {
//	        PopulationMultiplier = 0.65,
//	    },
//	}
//
// It is edited line-by-line rather than parsed into a tree and re-emitted,
// because the game rewrites this file itself and comparing it against a
// backup is a normal part of debugging a server. A structural rewrite would
// reorder and reformat hundreds of lines and make every diff useless.
type SandboxVars struct {
	lines           []string
	eol             string
	trailingNewline bool
}

// ParseSandboxVars reads the document. It never fails; a file that is not
// actually a sandbox table simply yields no addressable keys.
func ParseSandboxVars(data []byte) *SandboxVars {
	sv := &SandboxVars{eol: detectEOL(data), trailingNewline: bytes.HasSuffix(data, []byte("\n"))}
	s := strings.TrimSuffix(strings.TrimSuffix(string(data), "\n"), "\r")
	if len(data) == 0 {
		return sv
	}
	for _, line := range strings.Split(s, "\n") {
		sv.lines = append(sv.lines, strings.TrimSuffix(line, "\r"))
	}
	return sv
}

var (
	// A line that opens a nested table: "ZombieConfig = {".
	reSectionOpen = regexp.MustCompile(`^[ \t]*([A-Za-z_][A-Za-z0-9_]*)[ \t]*=[ \t]*\{`)
	// A line whose assignment is a table rather than a scalar. Such a line is
	// never a rewrite target: replacing "ZombieConfig = {" with a scalar
	// would orphan every key inside it and leave the file syntactically broken.
	reOpensTable = regexp.MustCompile(`=[ \t]*\{[ \t]*$`)
	reIndent     = regexp.MustCompile(`^[ \t]*`)
	// A Lua scalar we are willing to write: integer, float, boolean, or a
	// double-quoted string with no embedded unescaped quote.
	reLuaScalar = regexp.MustCompile(`^(-?\d+(\.\d+)?([eE][-+]?\d+)?|true|false|nil|"([^"\\]|\\.)*")$`)
)

// ValidateLuaScalar reports whether v can be written into the table without
// risking a syntax error.
//
// The bash implementation wrote whatever it was given, so a stray brace or
// newline in sandbox.txt produced a file the game could not load, and the
// server then failed to boot with a Lua error far away from the cause.
func ValidateLuaScalar(v string) error {
	if v == "" {
		return errors.New("gamecfg: empty value")
	}
	if !reLuaScalar.MatchString(v) {
		return fmt.Errorf("gamecfg: %q is not a Lua number, boolean or quoted string", v)
	}
	return nil
}

// splitKey divides "Section.Key" into its parts. A key with no dot is
// top-level.
func splitKey(dotted string) (section, leaf string) {
	if i := strings.IndexByte(dotted, '.'); i >= 0 {
		return dotted[:i], dotted[i+1:]
	}
	return "", dotted
}

// countBraces counts unquoted, uncommented braces on a line.
//
// A naive count would be thrown off by a brace inside a string value such as
// Map = "{foo}", or inside the "-- generated by gvm" header comment, and a
// single miscount shifts the depth for the entire rest of the file, so every
// later key resolves to the wrong nesting level.
func countBraces(line string) (opens, closes int) {
	inString := false
	escaped := false
	for i := 0; i < len(line); i++ {
		c := line[i]
		if inString {
			switch {
			case escaped:
				escaped = false
			case c == '\\':
				escaped = true
			case c == '"':
				inString = false
			}
			continue
		}
		switch {
		case c == '"':
			inString = true
		case c == '-' && i+1 < len(line) && line[i+1] == '-':
			return opens, closes // rest of the line is a comment
		case c == '{':
			opens++
		case c == '}':
			closes++
		}
	}
	return opens, closes
}

// walk visits every line with the nesting depth and enclosing section name
// that apply to it. depth 1 is a top-level key of SandboxVars; depth 2 is a
// key inside a nested table.
//
// Depth is reported as it stands *before* the line's own braces are counted,
// so the line "ZombieConfig = {" is itself seen at depth 1 and the keys
// beneath it at depth 2.
func (sv *SandboxVars) walk(visit func(i int, line string, depth int, section string) bool) {
	depth := 0
	section := ""
	for i, line := range sv.lines {
		if !visit(i, line, depth, section) {
			return
		}
		opens, closes := countBraces(line)
		if depth == 1 && opens > closes {
			if m := reSectionOpen.FindStringSubmatch(line); m != nil {
				section = m[1]
			}
		}
		depth += opens - closes
		if depth <= 1 {
			section = ""
		}
	}
}

// keyLineRE builds the matcher for an assignment to leaf.
//
// It is anchored and requires the "=" immediately after optional whitespace,
// so the key "Zombie" does not match the line "Zombies = 4".
func keyLineRE(leaf string) *regexp.Regexp {
	return regexp.MustCompile(`^[ \t]*` + regexp.QuoteMeta(leaf) + `[ \t]*=`)
}

// Get returns the raw Lua value assigned to a dotted key.
func (sv *SandboxVars) Get(dotted string) (string, bool) {
	section, leaf := splitKey(dotted)
	re := keyLineRE(leaf)
	var value string
	found := false

	sv.walk(func(_ int, line string, depth int, sec string) bool {
		if reOpensTable.MatchString(line) {
			return true
		}
		if !atKeyLevel(section, sec, depth) || !re.MatchString(line) {
			return true
		}
		rest := line[strings.IndexByte(line, '=')+1:]
		value = strings.TrimSuffix(strings.TrimSpace(rest), ",")
		value = strings.TrimSpace(value)
		found = true
		return false
	})
	return value, found
}

// atKeyLevel reports whether a line at this depth and section is the right
// scope for the requested key.
func atKeyLevel(wantSection, gotSection string, depth int) bool {
	if wantSection == "" {
		return depth == 1
	}
	return depth == 2 && gotSection == wantSection
}

// Set assigns a dotted key, rewriting the first matching line in place.
//
// It returns ErrKeyNotFound if the key is absent rather than appending it.
func (sv *SandboxVars) Set(dotted, value string) error {
	if err := ValidateLuaScalar(value); err != nil {
		return fmt.Errorf("%s: %w", dotted, err)
	}
	section, leaf := splitKey(dotted)
	re := keyLineRE(leaf)
	target := -1
	indent := ""

	sv.walk(func(i int, line string, depth int, sec string) bool {
		if reOpensTable.MatchString(line) {
			return true
		}
		if !atKeyLevel(section, sec, depth) || !re.MatchString(line) {
			return true
		}
		target = i
		indent = reIndent.FindString(line)
		return false
	})

	if target < 0 {
		return fmt.Errorf("%w: %s", ErrKeyNotFound, dotted)
	}
	// A trailing comma is always valid in a Lua table constructor, including
	// on the final entry, so writing one unconditionally is safe.
	sv.lines[target] = indent + leaf + " = " + value + ","
	return nil
}

// Delete removes every assignment of a dotted key and reports how many lines
// it removed.
//
// A line that opens a nested table is never a target: dropping
// "ZombieConfig = {" would orphan every key inside it and leave the file
// syntactically broken, which the game reports as a Lua error nowhere near the
// setting anyone was changing.
func (sv *SandboxVars) Delete(dotted string) int {
	section, leaf := splitKey(dotted)
	re := keyLineRE(leaf)
	drop := map[int]bool{}

	sv.walk(func(i int, line string, depth int, sec string) bool {
		if reOpensTable.MatchString(line) {
			return true
		}
		if !atKeyLevel(section, sec, depth) || !re.MatchString(line) {
			return true
		}
		drop[i] = true
		return true
	})

	if len(drop) == 0 {
		return 0
	}
	out := make([]string, 0, len(sv.lines)-len(drop))
	for i, line := range sv.lines {
		if drop[i] {
			continue
		}
		out = append(out, line)
	}
	sv.lines = out
	return len(drop)
}

// Keys lists every addressable dotted key, in file order.
//
// This is what makes validating an override file possible: a key that is not
// in this list does not exist in the running game's schema.
func (sv *SandboxVars) Keys() []string {
	var keys []string
	reAssign := regexp.MustCompile(`^[ \t]*([A-Za-z_][A-Za-z0-9_]*)[ \t]*=`)

	sv.walk(func(_ int, line string, depth int, sec string) bool {
		if reOpensTable.MatchString(line) {
			return true
		}
		m := reAssign.FindStringSubmatch(line)
		if m == nil {
			return true
		}
		switch {
		case depth == 1:
			keys = append(keys, m[1])
		case depth == 2 && sec != "":
			keys = append(keys, sec+"."+m[1])
		}
		return true
	})
	return keys
}

// Bytes renders the document back to its file representation.
func (sv *SandboxVars) Bytes() []byte {
	var b strings.Builder
	for i, line := range sv.lines {
		if i > 0 {
			b.WriteString(sv.eol)
		}
		b.WriteString(line)
	}
	if sv.trailingNewline && len(sv.lines) > 0 {
		b.WriteString(sv.eol)
	}
	return []byte(b.String())
}

func (sv *SandboxVars) String() string { return string(sv.Bytes()) }

// Override is one line of a sandbox override file.
type Override struct {
	Key   string
	Value string
	Line  int
}

// ParseOverrides reads the "Key = value" override format used by sandbox.txt.
//
// Text from "#" onward is a comment, blank lines are skipped, and all
// whitespace is stripped from the key. This matches the bash implementation
// exactly, including its one wart: because comments are stripped first, a "#"
// inside a quoted string value truncates it.
func ParseOverrides(data []byte) []Override {
	var out []Override
	for i, raw := range strings.Split(string(data), "\n") {
		line := raw
		if j := strings.IndexByte(line, '#'); j >= 0 {
			line = line[:j]
		}
		eq := strings.IndexByte(line, '=')
		if eq < 0 {
			continue
		}
		key := strings.Map(func(r rune) rune {
			if r == ' ' || r == '\t' || r == '\r' {
				return -1
			}
			return r
		}, line[:eq])
		value := strings.TrimSpace(line[eq+1:])
		if key == "" || value == "" {
			continue
		}
		out = append(out, Override{Key: key, Value: value, Line: i + 1})
	}
	return out
}

// ApplyResult reports the outcome of applying an override set.
type ApplyResult struct {
	Applied []Override
	// Skipped holds overrides whose key does not exist in the document, or
	// whose value is not a writable Lua scalar. These are warnings, not
	// failures: one bad line must not stop the other settings from applying.
	Skipped []SkippedOverride
}

// SkippedOverride is one override that could not be applied, and why.
type SkippedOverride struct {
	Override
	Err error
}

// ApplyOverrides applies every override it can, collecting the rest.
func (sv *SandboxVars) ApplyOverrides(overrides []Override) ApplyResult {
	var res ApplyResult
	for _, o := range overrides {
		if err := sv.Set(o.Key, o.Value); err != nil {
			res.Skipped = append(res.Skipped, SkippedOverride{Override: o, Err: err})
			continue
		}
		res.Applied = append(res.Applied, o)
	}
	return res
}
