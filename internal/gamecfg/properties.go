package gamecfg

import (
	"bytes"
	"fmt"
	"strings"
	"unicode/utf16"
	"unicode/utf8"
)

// Properties edits a java.util.Properties file: Minecraft's server.properties
// and eula.txt.
//
// The format is deceptively simple and every simplification is a bug someone
// has already shipped. A key ends at the first unescaped space, tab, '=' or
// ':', so "level-name" and "level name" are different keys and only one of
// them is what the operator meant. A line ending in an odd number of
// backslashes continues onto the next. The file is ISO-8859-1 on disk, not
// UTF-8, so a motd typed with a curly quote round-trips as mojibake unless it
// is written as a \uXXXX escape.
//
// The document is held as the file's own bytes, cut into entries. An entry
// nobody touched is written back exactly as it arrived, mixed line endings and
// all, so a diff after `gvm apply` shows the keys that changed and nothing
// else. That matters here more than anywhere: server.properties is owner:server
// and Minecraft rewrites it on every clean shutdown, so gvm's writes and the
// game's writes are compared against each other constantly.
type Properties struct {
	entries []propEntry
	// eol is the terminator to give a newly appended entry, taken from the
	// file rather than the host, because the file is read and written on Linux
	// and edited on whatever the operator uses.
	eol string
}

// propEntry is one logical line: an assignment, or any passthrough text
// (comment, blank line, or something unparseable that must survive regardless).
type propEntry struct {
	// raw is the entry's exact bytes including its line terminator. It is the
	// only thing Bytes writes for an untouched entry.
	raw []byte

	assign bool
	key    string // decoded
	value  string // decoded

	// indent and sep are the surrounding text of the first physical line, kept
	// so a rewrite of "  foo : bar" stays "  foo : new" instead of being
	// re-spelled as "foo=new" and showing up as a change nobody made.
	indent string
	sep    string
}

// ParseProperties reads a properties document. It never fails: a line it
// cannot read as an assignment becomes a passthrough entry.
func ParseProperties(data []byte) *Properties {
	p := &Properties{eol: "\n"}
	lines := splitKeepEOL(data)
	for _, ln := range lines {
		if e := lineEnding(ln); e != "" {
			p.eol = e
			break
		}
	}

	for i := 0; i < len(lines); i++ {
		raw := lines[i]
		text := string(latin1(trimEOL(raw)))

		if isPropComment(text) {
			p.entries = append(p.entries, propEntry{raw: raw})
			continue
		}

		// Consume continuation lines before deciding anything, so a value
		// broken across three lines is one entry and a Set collapses it
		// rather than leaving two orphaned fragments behind.
		joined := text
		for continuesLine(joined) && i+1 < len(lines) {
			i++
			raw = append(append([]byte{}, raw...), lines[i]...)
			joined = strings.TrimSuffix(joined, `\`) + strings.TrimLeft(string(latin1(trimEOL(lines[i]))), " \t\f")
		}

		e := propEntry{raw: raw}
		if indent, keyRaw, sep, valRaw, ok := splitPropLine(joined); ok {
			e.assign = true
			e.indent = indent
			e.sep = sep
			e.key = unescapeProps(keyRaw)
			e.value = unescapeProps(valRaw)
		}
		p.entries = append(p.entries, e)
	}
	return p
}

// isPropComment reports whether a line is a comment or blank. Java accepts
// both '#' and '!' as comment markers, and the "!" spelling shows up in files
// generated by tooling rather than by hand.
func isPropComment(line string) bool {
	t := strings.TrimLeft(line, " \t\f")
	return t == "" || strings.HasPrefix(t, "#") || strings.HasPrefix(t, "!")
}

// continuesLine reports whether a physical line ends in an ODD number of
// backslashes, which is the only case where the next line is a continuation.
// An even count is an escaped backslash that happens to sit at the end.
func continuesLine(s string) bool {
	n := 0
	for i := len(s) - 1; i >= 0 && s[i] == '\\'; i-- {
		n++
	}
	return n%2 == 1
}

// splitPropLine divides a logical line into its still-escaped parts.
func splitPropLine(s string) (indent, key, sep, value string, ok bool) {
	i := 0
	for i < len(s) && (s[i] == ' ' || s[i] == '\t' || s[i] == '\f') {
		i++
	}
	indent, s = s[:i], s[i:]

	end := 0
	for end < len(s) {
		c := s[end]
		if c == '\\' {
			end += 2
			continue
		}
		if c == ' ' || c == '\t' || c == '\f' || c == '=' || c == ':' {
			break
		}
		end++
	}
	if end > len(s) {
		end = len(s)
	}
	if end == 0 {
		return "", "", "", "", false
	}
	key, s = s[:end], s[end:]

	// The separator is optional whitespace, at most one '=' or ':', then more
	// optional whitespace. "foo bar" assigns bar to foo with no operator at all.
	j := 0
	for j < len(s) && (s[j] == ' ' || s[j] == '\t' || s[j] == '\f') {
		j++
	}
	if j < len(s) && (s[j] == '=' || s[j] == ':') {
		j++
		for j < len(s) && (s[j] == ' ' || s[j] == '\t' || s[j] == '\f') {
			j++
		}
	}
	return indent, key, s[:j], s[j:], true
}

// latin1 decodes ISO-8859-1 bytes: every byte is the code point of the same
// value. Reading the file as UTF-8 would turn a 0xE9 into a replacement
// character and write it back as one, corrupting a motd nobody edited.
func latin1(b []byte) []rune {
	out := make([]rune, len(b))
	for i, c := range b {
		out[i] = rune(c)
	}
	return out
}

func latin1Bytes(s string) []byte {
	var b bytes.Buffer
	for _, r := range s {
		if r > 0xFF {
			// Unreachable for text this package produced (escapeProps escapes
			// it) and for text read back from a Latin-1 file. Escaping rather
			// than substituting keeps a hand-fed string from silently losing
			// characters.
			writeUnicodeEscape(&b, r)
			continue
		}
		b.WriteByte(byte(r))
	}
	return b.Bytes()
}

func writeUnicodeEscape(b *bytes.Buffer, r rune) {
	if r > 0xFFFF {
		hi, lo := utf16.EncodeRune(r)
		fmt.Fprintf(b, "\\u%04X\\u%04X", hi, lo)
		return
	}
	fmt.Fprintf(b, "\\u%04X", r)
}

// unescapeProps applies Java's escape rules. An unknown escape yields the
// escaped character itself, which is what Properties.load does.
func unescapeProps(s string) string {
	var out []rune
	for i := 0; i < len(s); i++ {
		if s[i] != '\\' || i+1 >= len(s) {
			// Decode a rune rather than a byte: s already holds the file's
			// Latin-1 characters, so indexing by byte would split every one of
			// them above U+007F into its UTF-8 halves and re-encode them.
			r, n := utf8.DecodeRuneInString(s[i:])
			out = append(out, r)
			i += n - 1
			continue
		}
		i++
		switch s[i] {
		case 't':
			out = append(out, '\t')
		case 'n':
			out = append(out, '\n')
		case 'r':
			out = append(out, '\r')
		case 'f':
			out = append(out, '\f')
		case 'u':
			r, n := decodeUnicodeEscape(s[i+1:])
			if n == 0 {
				out = append(out, 'u')
				continue
			}
			i += n
			// A surrogate on its own is not a character; Java writes astral
			// code points as a pair and the halves must be rejoined here or
			// an emoji in a motd comes back as two replacement characters.
			if utf16.IsSurrogate(r) && i+6 < len(s) && s[i+1] == '\\' && s[i+2] == 'u' {
				if lo, n2 := decodeUnicodeEscape(s[i+3:]); n2 > 0 {
					if joined := utf16.DecodeRune(r, lo); joined != 0xFFFD {
						out = append(out, joined)
						i += 2 + n2
						continue
					}
				}
			}
			out = append(out, r)
		default:
			r, n := utf8.DecodeRuneInString(s[i:])
			out = append(out, r)
			i += n - 1
		}
	}
	return string(out)
}

func decodeUnicodeEscape(s string) (rune, int) {
	if len(s) < 4 {
		return 0, 0
	}
	var r rune
	for i := 0; i < 4; i++ {
		c := s[i]
		var d rune
		switch {
		case c >= '0' && c <= '9':
			d = rune(c - '0')
		case c >= 'a' && c <= 'f':
			d = rune(c-'a') + 10
		case c >= 'A' && c <= 'F':
			d = rune(c-'A') + 10
		default:
			return 0, 0
		}
		r = r<<4 | d
	}
	return r, 4
}

// escapeProps escapes a key or value the way java.util.Properties.store does.
//
// Escaping '=', ':', '#' and '!' inside a value is not strictly required —
// only the key half is ambiguous — but Minecraft rewrites server.properties
// with Properties.store on every clean shutdown, so writing what the game
// writes means the drift check after a stop reports nothing instead of
// reporting every value as re-escaped.
func escapeProps(s string, isKey bool) string {
	var b bytes.Buffer
	for i, r := range s {
		switch r {
		case '\\':
			b.WriteString(`\\`)
		case '\t':
			b.WriteString(`\t`)
		case '\n':
			b.WriteString(`\n`)
		case '\r':
			b.WriteString(`\r`)
		case '\f':
			b.WriteString(`\f`)
		case ' ':
			// In a key a space ends the key. In a value only a leading space
			// is at risk, because it would be eaten as separator padding.
			if isKey || i == 0 {
				b.WriteString(`\ `)
			} else {
				b.WriteByte(' ')
			}
		case '=', ':', '#', '!':
			b.WriteByte('\\')
			b.WriteRune(r)
		default:
			if r < 0x20 || r > 0xFF {
				writeUnicodeEscape(&b, r)
				continue
			}
			b.WriteRune(r)
		}
	}
	return b.String()
}

// Get returns the value of a key.
//
// The LAST assignment wins, because Properties.load puts each line into a map
// in order and that is the value the server actually reads. Returning the
// first would report a value the game is not using.
func (p *Properties) Get(key string) (string, bool) {
	value, found := "", false
	for _, e := range p.entries {
		if e.assign && e.key == key {
			value, found = e.value, true
		}
	}
	return value, found
}

// Set assigns a key, rewriting the first existing assignment in place and
// removing any later duplicates, then appending if there was none.
//
// Rewriting the first keeps the file's ordering; removing the rest is what
// makes the result unambiguous, since a stale later copy is the one the game
// would read.
func (p *Properties) Set(key, value string) error {
	if err := (propertiesCodec{}).KeySyntax(key); err != nil {
		return err
	}

	out := make([]propEntry, 0, len(p.entries)+1)
	written := false
	for _, e := range p.entries {
		if !e.assign || e.key != key {
			out = append(out, e)
			continue
		}
		if written {
			continue
		}
		e.value = value
		e.raw = p.renderEntry(e, lineEnding(e.raw))
		out = append(out, e)
		written = true
	}

	if !written {
		if n := len(out); n > 0 && lineEnding(out[n-1].raw) == "" {
			// The file did not end in a newline; appending without one would
			// glue the new key onto whatever the last line was.
			out[n-1].raw = append(append([]byte{}, out[n-1].raw...), p.eol...)
		}
		e := propEntry{assign: true, key: key, value: value, sep: "="}
		e.raw = p.renderEntry(e, p.eol)
		out = append(out, e)
	}
	p.entries = out
	return nil
}

func (p *Properties) renderEntry(e propEntry, eol string) []byte {
	sep := e.sep
	if sep == "" {
		// A bare "foo" line has no separator; without this the key and the new
		// value would be concatenated into one token.
		sep = "="
	}
	line := e.indent + escapeProps(e.key, true) + sep + escapeProps(e.value, false)
	return append(latin1Bytes(line), eol...)
}

// Delete removes every assignment of a key.
func (p *Properties) Delete(key string) int {
	out := make([]propEntry, 0, len(p.entries))
	n := 0
	for _, e := range p.entries {
		if e.assign && e.key == key {
			n++
			continue
		}
		out = append(out, e)
	}
	p.entries = out
	return n
}

// Keys lists every assigned key in file order.
func (p *Properties) Keys() []string {
	var keys []string
	for _, e := range p.entries {
		if e.assign {
			keys = append(keys, e.key)
		}
	}
	return dedupe(keys)
}

// Bytes renders the document back to ISO-8859-1.
func (p *Properties) Bytes() []byte {
	var b bytes.Buffer
	for _, e := range p.entries {
		b.Write(e.raw)
	}
	return b.Bytes()
}

func (p *Properties) String() string { return string(p.Bytes()) }

type propertiesCodec struct{}

func (propertiesCodec) Name() string { return "java_properties" }

func (propertiesCodec) Parse(data []byte) (Doc, error) { return ParseProperties(data), nil }

// New is allowed: eula.txt is a gvm-owned file that has to exist before the
// server will start at all, and an empty server.properties is a file Minecraft
// fills in from its own defaults on first boot.
func (propertiesCodec) New() (Doc, error) { return &Properties{eol: "\n"}, nil }

func (propertiesCodec) KeySyntax(key string) error {
	if err := plainKeySyntax(key); err != nil {
		return err
	}
	if strings.ContainsAny(key, "\f") {
		return fmt.Errorf("config key %q contains a form feed, which ends the key", key)
	}
	return nil
}
