package gamecfg

import (
	"bytes"
	"errors"
	"fmt"
	"sort"
	"strings"
	"sync"
)

// Doc is one parsed configuration file, held in a form that can be written
// back.
//
// Every implementation except owned_lines guarantees the same two properties,
// and the test for each codec asserts both against a real-world sample:
//
//   - Parse followed by Bytes with no mutation returns the input byte for byte.
//   - One Set changes one key and nothing else. Comments, ordering, blank
//     lines, indentation and unrecognised keys all survive.
//
// The guarantee exists because game servers own their config files and rewrite
// them on their own schedule. Anything gvm discards on a write is a setting an
// admin made in-game, or a hand-fix applied at 3am, and losing it looks like
// gvm working correctly right up to the point the server behaves differently.
type Doc interface {
	// Get returns the value a key currently holds, decoded out of whatever
	// escaping the format uses.
	Get(key string) (string, bool)

	// Set assigns a key. Codecs whose file is generated from the game's own
	// schema return ErrKeyNotFound for a key the file lacks rather than
	// inventing it: the game ignores a key it does not know, so an invented
	// key looks like it worked and silently does nothing.
	Set(key, value string) error

	// Delete removes every assignment of a key and reports how many it removed.
	Delete(key string) int

	// Keys lists every addressable key, in file order, without duplicates.
	Keys() []string

	// Bytes renders the document back to its on-disk representation.
	Bytes() []byte
}

// Codec is one config file format, addressed from a manifest by Name.
type Codec interface {
	Name() string

	Parse(data []byte) (Doc, error)

	// New builds an empty document. It returns ErrCannotCreate for formats
	// whose file only the game can produce, which is what makes
	// `create_if_missing: true` on such a file a validation error rather than
	// a half-written config the server refuses to load.
	New() (Doc, error)

	// KeySyntax validates a key at MANIFEST LOAD time, so a typo in a config
	// key fails `gvm game validate` and not a restart at 3am. It knows nothing
	// about any particular file: it rejects only keys this format could never
	// address, whatever the file contains.
	KeySyntax(key string) error
}

var (
	// ErrCannotCreate means the game must generate this file. gvm edits it
	// afterwards; writing a synthetic one first produces a config the server
	// either rejects or silently replaces.
	ErrCannotCreate = errors.New("gamecfg: this file must be generated by the game")

	// ErrUnsupported means the format cannot express the requested edit. It is
	// always a refusal to guess, never a partial write.
	ErrUnsupported = errors.New("gamecfg: unsupported edit")
)

var (
	registryMu sync.RWMutex
	codecs     = map[string]Codec{}
)

// Register adds a codec to the registry. It panics on a duplicate name,
// because two codecs answering to one manifest `format:` would make the winner
// depend on package initialisation order.
func Register(c Codec) {
	registryMu.Lock()
	defer registryMu.Unlock()
	name := c.Name()
	if _, dup := codecs[name]; dup {
		panic("gamecfg: duplicate codec registration: " + name)
	}
	codecs[name] = c
}

// Lookup returns the codec registered under name.
func Lookup(name string) (Codec, bool) {
	registryMu.RLock()
	defer registryMu.RUnlock()
	c, ok := codecs[name]
	return c, ok
}

// Formats lists every registered codec name, sorted.
//
// internal/spec keeps its own copy of this list, because manifest validation
// must work whether or not anything imported this package for its side
// effects. codec_test.go asserts the two agree.
func Formats() []string {
	registryMu.RLock()
	defer registryMu.RUnlock()
	out := make([]string, 0, len(codecs))
	for n := range codecs {
		out = append(out, n)
	}
	sort.Strings(out)
	return out
}

func init() {
	Register(iniCodec{})
	Register(sandboxCodec{})
	Register(propertiesCodec{})
	Register(xmlPropsCodec{})
	Register(ueSettingsCodec{})
	Register(jsonPathCodec{})
	Register(tomlKVCodec{})
	Register(ownedLinesCodec{})
}

// plainKeySyntax is the floor every format shares: a key that is empty, padded,
// or spans lines is a mistake in the manifest under any codec.
func plainKeySyntax(key string) error {
	if key == "" {
		return errors.New("empty config key")
	}
	if strings.TrimSpace(key) != key {
		return fmt.Errorf("config key %q has leading or trailing whitespace", key)
	}
	if strings.ContainsAny(key, "\r\n") {
		return fmt.Errorf("config key %q spans lines", key)
	}
	return nil
}

// dottedSegments splits a path key and checks that no segment is empty, so
// "a..b" and ".a" fail at load rather than resolving to something surprising.
func dottedSegments(key string) ([]string, error) {
	if err := plainKeySyntax(key); err != nil {
		return nil, err
	}
	parts := strings.Split(key, ".")
	for _, p := range parts {
		if strings.TrimSpace(p) == "" {
			return nil, fmt.Errorf("config key %q has an empty path segment", key)
		}
	}
	return parts, nil
}

// splitKeepEOL divides data into physical lines that still carry their own line
// terminator.
//
// Codecs that rebuild a file from a line list need this rather than
// strings.Split: a file with mixed CRLF and LF endings, which is what an
// operator's editor produces on a Windows workstation, would otherwise be
// normalised on a write that changed one unrelated key.
func splitKeepEOL(data []byte) [][]byte {
	var out [][]byte
	for len(data) > 0 {
		i := bytes.IndexByte(data, '\n')
		if i < 0 {
			out = append(out, data)
			break
		}
		out = append(out, data[:i+1])
		data = data[i+1:]
	}
	return out
}

// lineEnding returns the terminator a line carries, or "" for a final line
// that has none.
func lineEnding(line []byte) string {
	switch {
	case bytes.HasSuffix(line, []byte("\r\n")):
		return "\r\n"
	case bytes.HasSuffix(line, []byte("\n")):
		return "\n"
	}
	return ""
}

// trimEOL returns the line's content without its terminator.
func trimEOL(line []byte) []byte {
	return line[:len(line)-len(lineEnding(line))]
}

// splice replaces the byte range [start,end) of b with text.
//
// It always returns fresh bytes. Every Doc hands its buffer out of Bytes()
// without copying, so a splice that reused b's array would rewrite bytes a
// previous caller is still holding.
func splice(b []byte, start, end int, text string) []byte {
	out := make([]byte, 0, start+len(text)+len(b)-end)
	out = append(out, b[:start]...)
	out = append(out, text...)
	return append(out, b[end:]...)
}

// spliceLine splices within a line's content, keeping the terminator that line
// carries. Offsets are relative to the line WITHOUT its EOL, which is what the
// line-oriented codecs record.
func spliceLine(line []byte, start, end int, text string) []byte {
	return append(splice(trimEOL(line), start, end, text), lineEnding(line)...)
}

// dedupe keeps the first occurrence of each name, preserving file order.
func dedupe(in []string) []string {
	seen := make(map[string]bool, len(in))
	out := make([]string, 0, len(in))
	for _, s := range in {
		if seen[s] {
			continue
		}
		seen[s] = true
		out = append(out, s)
	}
	if len(out) == 0 {
		return nil
	}
	return out
}

// --- pz_ini -----------------------------------------------------------------

type iniCodec struct{}

func (iniCodec) Name() string { return "pz_ini" }

func (iniCodec) Parse(data []byte) (Doc, error) { return iniDoc{ParseINI(data)}, nil }

// New refuses: Project Zomboid writes <servername>.ini itself on first boot,
// populated from the version's own defaults. A file gvm invented would be
// missing every key the game did not ask us about, and pz.first_boot exists
// precisely so the server generates it before anything is edited.
func (iniCodec) New() (Doc, error) {
	return nil, fmt.Errorf("%w: Project Zomboid generates the .ini on first boot", ErrCannotCreate)
}

func (iniCodec) KeySyntax(key string) error {
	if err := plainKeySyntax(key); err != nil {
		return err
	}
	if strings.Contains(key, "=") {
		return fmt.Errorf("config key %q contains '=', which ends the key in a pz_ini file", key)
	}
	return nil
}

// iniDoc adapts *INI to Doc.
//
// INI.Set panics on a key it cannot write, which suits its direct callers —
// they have already validated. Reached through Doc it is one entry in an apply
// loop over a manifest, where a bad key has to be a returned error the operator
// can read next to the file it came from.
type iniDoc struct{ *INI }

func (d iniDoc) Set(key, value string) error {
	if err := (iniCodec{}).KeySyntax(key); err != nil {
		return err
	}
	d.INI.Set(key, value)
	return nil
}

// --- lua_sandboxvars --------------------------------------------------------

type sandboxCodec struct{}

func (sandboxCodec) Name() string { return "lua_sandboxvars" }

func (sandboxCodec) Parse(data []byte) (Doc, error) { return ParseSandboxVars(data), nil }

func (sandboxCodec) New() (Doc, error) {
	return nil, fmt.Errorf("%w: Project Zomboid generates SandboxVars.lua from its own schema", ErrCannotCreate)
}

// KeySyntax enforces the two levels the file actually has. SandboxVars is a
// table of scalars and one level of nested tables, so "ZombieConfig.Foo.Bar"
// can never resolve — and reported at load it names the manifest line, where
// reported at apply it would be one skipped key in a warning list.
func (sandboxCodec) KeySyntax(key string) error {
	parts, err := dottedSegments(key)
	if err != nil {
		return err
	}
	if len(parts) > 2 {
		return fmt.Errorf("config key %q is more than two levels deep; SandboxVars nests exactly once", key)
	}
	for _, p := range parts {
		if !isLuaIdent(p) {
			return fmt.Errorf("config key %q: %q is not a Lua identifier", key, p)
		}
	}
	return nil
}

func isLuaIdent(s string) bool {
	if s == "" {
		return false
	}
	for i := 0; i < len(s); i++ {
		c := s[i]
		switch {
		case c >= 'a' && c <= 'z', c >= 'A' && c <= 'Z', c == '_':
		case c >= '0' && c <= '9' && i > 0:
		default:
			return false
		}
	}
	return true
}
