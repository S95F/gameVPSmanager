package gamecfg

import (
	"fmt"
	"strings"
)

// OwnedLinesKey is the only key this codec accepts. It is spelled with leading
// underscores because it is not a setting the file contains — it IS the file.
const OwnedLinesKey = "__lines"

// OwnedLinesHeader is written as the first line of every file this codec
// produces, so the discard rule is visible to whoever opens the file rather
// than only to whoever reads the manifest.
const OwnedLinesHeader = "# Generated by gvm. The whole file is replaced on every apply; edits here are lost."

// OwnedLines is THE ONE CODEC IN THIS PACKAGE THAT DOES NOT PRESERVE UNKNOWN
// CONTENT. A write replaces the entire file. Comments, ordering, blank lines
// and anything an operator added by hand are discarded.
//
// That is correct for exactly one kind of file: one gvm generates in full from
// a single manifest variable, where there is no game-owned content to lose.
// Minecraft's user_jvm_args.txt is the case it exists for — the whole file is
// the JVM argument list, and merging into it would produce a heap size that is
// half the old value and half the new one, which the JVM accepts and then runs
// with whichever came last.
//
// Every other codec here guarantees the opposite, so the difference has to be
// obvious in review: the format is named owned_lines in the manifest, the only
// key is __lines, and the file itself carries OwnedLinesHeader saying so.
//
// Until something is Set, the document renders back byte for byte. Reading a
// file does not destroy it; writing to it does.
type OwnedLines struct {
	raw []byte
	// value is nil until Set replaces the file. Keeping the distinction is what
	// makes a parse-and-render with no edit a true no-op, so a `gvm apply
	// --diff` over an unchanged instance does not report this file as rewritten.
	value *string
	eol   string
}

// ParseOwnedLines reads the file. It never fails.
func ParseOwnedLines(data []byte) *OwnedLines {
	o := &OwnedLines{raw: append([]byte{}, data...), eol: "\n"}
	for _, ln := range splitKeepEOL(data) {
		if e := lineEnding(ln); e != "" {
			o.eol = e
			break
		}
	}
	return o
}

// Get returns the file's body: everything after the header this codec writes.
func (o *OwnedLines) Get(key string) (string, bool) {
	if key != OwnedLinesKey {
		return "", false
	}
	if o.value != nil {
		return *o.value, true
	}
	return ownedBody(string(o.raw)), true
}

// ownedBody strips OwnedLinesHeader and nothing else, so reading back a file
// this codec wrote returns what was written rather than the header plus what
// was written.
//
// It must not strip every leading '#' line. A value may legitimately begin with
// a comment — a Java @argfile takes them — and a value that does not survive the
// write/read cycle makes the drift check fire forever: desired never equals
// observed, so every apply rewrites byte-identical content and every status
// shows a restart pending.
//
// The CRLF normalisation comes first so one TrimPrefix covers both endings.
func ownedBody(s string) string {
	s = strings.ReplaceAll(s, "\r\n", "\n")
	s = strings.TrimPrefix(s, OwnedLinesHeader+"\n")
	return strings.TrimSuffix(s, "\n")
}

// Set replaces the file's entire contents.
//
// Only OwnedLinesKey is accepted. A second key would imply the file has
// structure, and it does not: there is nothing here to merge into.
func (o *OwnedLines) Set(key, value string) error {
	if key != OwnedLinesKey {
		return fmt.Errorf("%w: owned_lines writes the whole file through %q and has no key %q",
			ErrKeyNotFound, OwnedLinesKey, key)
	}
	v := value
	o.value = &v
	return nil
}

// Delete empties the file, leaving the header. It reports 1 when there was
// anything to remove.
func (o *OwnedLines) Delete(key string) int {
	if key != OwnedLinesKey {
		return 0
	}
	body, _ := o.Get(key)
	if body == "" {
		return 0
	}
	empty := ""
	o.value = &empty
	return 1
}

// Keys reports the single key, always, even for an empty file: the key is a
// property of the format and not of the contents.
func (o *OwnedLines) Keys() []string { return []string{OwnedLinesKey} }

// Bytes renders the file. With nothing set it returns the input unchanged.
func (o *OwnedLines) Bytes() []byte {
	if o.value == nil {
		return o.raw
	}
	var b strings.Builder
	b.WriteString(OwnedLinesHeader)
	b.WriteString(o.eol)
	if *o.value == "" {
		return []byte(b.String())
	}
	for i, ln := range strings.Split(strings.ReplaceAll(*o.value, "\r\n", "\n"), "\n") {
		if i > 0 {
			b.WriteString(o.eol)
		}
		b.WriteString(strings.TrimSuffix(ln, "\r"))
	}
	b.WriteString(o.eol)
	return []byte(b.String())
}

func (o *OwnedLines) String() string { return string(o.Bytes()) }

type ownedLinesCodec struct{}

func (ownedLinesCodec) Name() string { return "owned_lines" }

func (ownedLinesCodec) Parse(data []byte) (Doc, error) { return ParseOwnedLines(data), nil }

func (ownedLinesCodec) New() (Doc, error) { return ParseOwnedLines(nil), nil }

// KeySyntax accepts nothing but __lines, so a manifest that gives an
// owned_lines file a normal-looking key list is refused instead of applying no
// settings and reporting success. internal/cli wires this into `gvm game
// validate`; internal/spec cannot, because it must not import this package.
func (ownedLinesCodec) KeySyntax(key string) error {
	if key != OwnedLinesKey {
		return fmt.Errorf("owned_lines has exactly one key, %q; %q would be silently ignored because this format writes the whole file at once",
			OwnedLinesKey, key)
	}
	return nil
}
